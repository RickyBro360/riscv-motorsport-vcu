"""
tracks.py — the circuit library (SOFTWARE/tracks/tracks.json, generated by
SOFTWARE/tracks/build_tracks.py from the same data the VCU's track_maps.h is built from).

Everything position-related the ground station says about the car — which corner it
is in, what the flaps should be doing, what the full-scale car would be feeling —
comes from these maps and the VCU-reported lap fraction. Geometry is real (public
GeoJSON); speeds, g and aero zones are MODELLED and labelled as such everywhere.
"""
from __future__ import annotations

import json
import math
import os
from functools import lru_cache
from pathlib import Path

TRACKS_PATH = Path(os.environ.get(
    "VCU_TRACKS_PATH", Path(__file__).resolve().parents[2] / "tracks" / "tracks.json"))


@lru_cache(maxsize=1)
def load() -> dict:
    return json.loads(TRACKS_PATH.read_text(encoding="utf-8"))


def all_tracks() -> list[dict]:
    return load()["tracks"]


def default_id() -> int:
    return int(load()["defaultTrackId"])


def get(track_id: int | None) -> dict:
    tr = all_tracks()
    if track_id is None or not (0 <= int(track_id) < len(tr)):
        return tr[default_id()]
    return tr[int(track_id)]


def summary() -> list[dict]:
    return [{"id": t["id"], "code": t["code"], "name": t["name"], "grandPrix": t["grandPrix"],
             "fullName": t["fullName"], "lengthM": t["lengthM"], "model": t["model"],
             "corners": len(t["corners"]), "straightZones": len(t["straightZones"])}
            for t in all_tracks()]


def _idx(track: dict, pos: float) -> int:
    n = len(track["series"]["speedKmh"])
    p = pos - math.floor(pos) if math.isfinite(pos) else 0.0
    return min(n - 1, int(p * n))


def _flag_at(track: dict, pos: float) -> bool:
    return bool(track["series"]["straight"][_idx(track, pos)])


def straight_at(track: dict, pos: float, open_delay_m: float = 0.0, close_early_m: float = 0.0) -> bool:
    """Same rule as vcu_logic.h trackSample(): the map flag, shrunk by the offsets."""
    L = track["lengthM"]
    return (_flag_at(track, pos) and _flag_at(track, pos - open_delay_m / L)
            and _flag_at(track, pos + close_early_m / L))


def sample(track: dict, pos: float) -> dict:
    s, i = track["series"], _idx(track, pos)
    return {"speedKmh": s["speedKmh"][i], "steerDeg": s["steerDeg"][i], "latG": s["latG"][i],
            "longG": s["longG"][i], "straight": s["straight"][i], "braking": s["braking"][i],
            "sector": min(2, int((pos % 1.0) * 3)), "index": i}


def corner_at(track: dict, pos: float) -> dict | None:
    """Nearest detected corner within ±2 % of the lap."""
    best, best_d = None, 0.02
    for c in track["corners"]:
        d = abs(((c["pos"] - pos) + 0.5) % 1.0 - 0.5)
        if d < best_d:
            best, best_d = c, d
    return best


def next_event(track: dict, pos: float, open_delay_m: float = 0.0, close_early_m: float = 0.0) -> dict | None:
    """The next straight/corner-mode transition ahead of `pos` (lap fraction), with its
    distance in full-scale metres."""
    L = track["lengthM"]
    now = straight_at(track, pos, open_delay_m, close_early_m)
    n = len(track["series"]["straight"])
    for k in range(1, n):
        p = pos + k / n
        if straight_at(track, p, open_delay_m, close_early_m) != now:
            return {"type": "corner_mode" if now else "straight_mode", "inFrac": k / n, "inM": round(k / n * L, 1),
                    "corner": corner_at(track, p + 0.01)}
    return None
