/* FW 2.3 — ONLY THINGS THAT CAN HURT THE CAR STOP THE MOTOR.
 *   FAULT (motor off, auto-clears 1 s after the cause is gone, never latches):
 *       supply under-voltage, over-current, motor / battery over-temperature, and loss of the
 *       driver's link while DRIVING. (FW 2.3.1: a stalled task is a WARNING — see below.)
 *   WARNING (shown on the dashboard, nothing stops):
 *       sensor read timeouts, implausible readings, failed self-test items, servo position
 *       mismatch, CAN / LoRa link, motor stall (the stall watchdog itself ends the run).
 *   CRITICAL is no longer raised by any sensor: the only latching stop is the E-STOP button.
 * Steering and flaps keep working in FAULT; only E-STOP / boot put them to failsafe.
 * (FW 2.2 latched an E-STOP on a watchdog glitch and parked the car in FAULT forever after
 *  one failed self-test item, e.g. a missing DS18B20 or a gyro calibration disturbed by a
 *  servo twitch — that is what made it look like it "kept stopping".) */
class SafetyManager {
 public:
  SafetyResult evaluate(const SafetyInputs &in) {
    SafetyResult r;
    auto raise = [&r](uint32_t bit, Severity sev) {
      r.fault_flags |= bit;
      if (sev > r.worst) r.worst = sev;
    };
    // FW 2.3.1: WARNING. A task that really hangs is caught by the ESP32's own task watchdog (3 s ->
    // reboot, and the motor pin's pull-down stops the motor). This 1 s software check kept the car
    // in FAULT on the classic stand-in's sensor-task stalls; it is now logged ([WDOG], `diag`).
    if (!in.watchdog_ok) raise(FAULT_BIT_WATCHDOG_TIMEOUT, SEV_WARNING);

    bool running = in.state >= VS_IDLE;  // don't flag timeouts while booting
    const bool power_stale = in.power_sensor_present && in.power_age_ms > CFG_POWER_TIMEOUT_MS;
    if (running && (in.imu_age_ms > CFG_IMU_TIMEOUT_MS || power_stale ||
                    (in.temp_sensors_present && in.temp_age_ms > CFG_TEMP_TIMEOUT_MS)))
      raise(FAULT_BIT_SENSOR_TIMEOUT, SEV_WARNING);

    if (running && !in.can_link_ok) raise(FAULT_BIT_CAN_TIMEOUT, SEV_WARNING);
    if (running && !in.lora_link_ok) raise(FAULT_BIT_LORA_TIMEOUT, SEV_WARNING);

    bool v_valid = in.power_sensor_present && in.battery_voltage_v > CFG_BATTERY_VOLT_MIN_VALID &&
                   in.battery_voltage_v < CFG_BATTERY_VOLT_MAX_VALID;
    if (in.any_non_finite || (running && in.power_sensor_present && !v_valid))
      raise(FAULT_BIT_INVALID_SENSOR, SEV_WARNING);

    float undervolt = CFG_CELL_UNDERVOLT_V * CFG_BATTERY_CELLS;
    if (undervolt_.update(v_valid && in.battery_voltage_v < undervolt, in.now_ms,
                          CFG_UNDERVOLT_PERSIST_MS))
      raise(FAULT_BIT_BATTERY_UNDERVOLT, SEV_FAULT);

    if (overcurrent_.update(in.power_sensor_present && std::fabs(in.battery_current_a) > CFG_BATTERY_OVERCURRENT_A, in.now_ms,
                            CFG_OVERCURRENT_PERSIST_MS))
      raise(FAULT_BIT_OVERCURRENT, SEV_FAULT);

    if (batt_ot_.update(in.temp_sensors_present && in.battery_temp_c > CFG_BATTERY_OVERTEMP_C,
                        in.now_ms, CFG_OVERTEMP_PERSIST_MS))
      raise(FAULT_BIT_BATTERY_OVERTEMP, SEV_FAULT);
    if (motor_ot_.update(in.motor_temp_available && in.motor_temp_c > CFG_MOTOR_OVERTEMP_C,
                         in.now_ms, CFG_OVERTEMP_PERSIST_MS))
      raise(FAULT_BIT_MOTOR_OVERTEMP, SEV_FAULT);

    if (in.steering_pos_error) raise(FAULT_BIT_SERVO_POSITION_ERROR, SEV_WARNING);
    if (in.aero_pos_error) raise(FAULT_BIT_AERO_POSITION_ERROR, SEV_WARNING);
    if (in.ai_last_rejected) raise(FAULT_BIT_INVALID_AI_REC, SEV_INFO);
    if (in.self_test_failed) raise(FAULT_BIT_SELF_TEST_FAILED, SEV_WARNING);
    if (in.motor_stall) raise(FAULT_BIT_MOTOR_STALL, SEV_WARNING);
    if (!in.driver_link_ok && (in.state == VS_DRIVE || in.state == VS_ARMED))
      raise(FAULT_BIT_COMM_LOSS, in.state == VS_DRIVE ? SEV_FAULT : SEV_WARNING);
    if (in.state == VS_EMERGENCY_STOP) raise(FAULT_BIT_ESTOP_ACTIVE, SEV_INFO);

    // No power sensor in the BUILD = no way to see undervoltage/overcurrent: never allow the motor.
    r.permits_drive = r.worst < SEV_FAULT && in.power_sensor_present;
    r.aero_failsafe = false;   // FW 2.3: flaps go to failsafe only on E-STOP / boot / aero mode 2
    return r;
  }

 private:
  Persist undervolt_, overcurrent_, batt_ot_, motor_ot_;
};

// =============================================================================
// 5. AI RECOMMENDATION VALIDATION  (the VCU's authority boundary)
// =============================================================================
struct AiWingRecommendation {
  float lf = 0, rf = 0, lr = 0, rr = 0;
  float confidence = 0;
  uint32_t timestamp_ms = 0;  // stamped at CAN arrival by the VCU, not by the sender
  uint8_t sequence = 0;
  bool valid = false;         // false = never populated / malformed
};

enum AiReason : uint8_t {
  AI_ACCEPTED = 0, AI_REJ_NOT_POPULATED, AI_REJ_LOW_CONFIDENCE, AI_REJ_FUTURE_TIMESTAMP,
  AI_REJ_STALE, AI_REJ_NON_FINITE, AI_REJ_OUT_OF_RANGE, AI_REJ_SAFE_STATE,
  AI_REJ_MODE_DISABLED, AI_NONE_RECEIVED,
};

inline const char *aiReasonName(AiReason r) {
  static const char *n[] = {"accepted", "not_populated", "low_confidence", "future_timestamp",
                            "stale", "non_finite", "out_of_range", "safe_state_override",
                            "ai_mode_disabled", "none_received"};
  return r <= AI_NONE_RECEIVED ? n[r] : "unknown";
}

/* Same checks, same order, same thresholds as HARDWARE/tests/vcu_sim.py
 * ai_recommendation_is_valid(). */
inline AiReason aiRecommendationCheck(const AiWingRecommendation &rec, uint32_t now_ms) {
  if (!rec.valid) return AI_REJ_NOT_POPULATED;
  if (!finite(rec.confidence) || rec.confidence < CFG_AI_MIN_CONFIDENCE) return AI_REJ_LOW_CONFIDENCE;
  if (now_ms < rec.timestamp_ms) return AI_REJ_FUTURE_TIMESTAMP;
  if (now_ms - rec.timestamp_ms > CFG_AI_MAX_STALENESS_MS) return AI_REJ_STALE;
  const float ch[4] = {rec.lf, rec.rf, rec.lr, rec.rr};
  for (float v : ch) {
    if (!finite(v)) return AI_REJ_NON_FINITE;
    if (v < CFG_WING_ANGLE_MIN_DEG || v > CFG_WING_ANGLE_MAX_DEG) return AI_REJ_OUT_OF_RANGE;
  }
  return AI_ACCEPTED;
}
inline bool aiRecommendationIsValid(const AiWingRecommendation &rec, uint32_t now_ms) {
  return aiRecommendationCheck(rec, now_ms) == AI_ACCEPTED;
}

// =============================================================================
// 6. ACTIVE AERO CONTROLLER  (4 independent flaps: LF, RF, LR, RR)
// =============================================================================
enum AeroChannel : uint8_t { AERO_LF = 0, AERO_RF = 1, AERO_LR = 2, AERO_RR = 3 };
enum AeroMode : uint8_t { AERO_MODE_BASELINE = 0, AERO_MODE_AI_ASSIST = 1, AERO_MODE_FAILSAFE_HOLD = 2 };

struct AeroInputs {
  float speed_kmh = 0;
  float lat_g = 0;             // +ve = acceleration toward vehicle LEFT (see PinoutAndWiring.md IMU axes)
  VehicleState state = VS_IDLE;
  AeroMode mode = AERO_MODE_AI_ASSIST;
  bool force_failsafe = false; // from SafetyResult.aero_failsafe
  float dt_s = 0.01f;
  // Stage 2d track run: the map (TrackRunner) supplies the baseline instead of the
  // speed/lateral-g formula. The AI blend, rate limit and failsafe are unchanged.
  bool baseline_override = false;
  float baseline[4] = {0, 0, 0, 0};
  bool allow_ai = true;        // FW 2.3: AI recommendations are blended in circuit runs only
};

struct AeroOutput {
  float desired[4] = {0, 0, 0, 0};  // after AI blend, before rate limiting
  float target[4] = {0, 0, 0, 0};   // rate-limited setpoint sent to servos
  AiReason ai_reason = AI_NONE_RECEIVED;
  bool ai_applied = false;
};

/* Physics baseline + optional asymmetric lateral term. With
 * lateral_gain = 0 and no rate limiting this is exactly vcu_sim.py's
 * simulate_actuator_target() — asserted in the host test. The asymmetric
 * sign convention matches SOFTWARE/backend/app/ai_engine.py
 * (_recommended_wing: right flaps = base + k*g_lat). */
inline void aeroBaseline(float speed_kmh, float lat_g, float lateral_gain, float out[4]) {
  float base, lat = 0.0f;
  if (!finite(speed_kmh) || speed_kmh < CFG_AERO_MIN_SPEED_KMH) {
    base = CFG_WING_FAILSAFE_ANGLE_DEG;
  } else {
    base = clampf((speed_kmh - CFG_AERO_MIN_SPEED_KMH) * CFG_AERO_SPEED_GAIN_DEG_PER_KMH,
                  CFG_WING_ANGLE_MIN_DEG, CFG_WING_ANGLE_MAX_DEG);
    if (finite(lat_g)) lat = clampf(lat_g * lateral_gain, -CFG_AERO_LATERAL_MAX_DEG, CFG_AERO_LATERAL_MAX_DEG);
  }
  out[AERO_LF] = clampf(base - lat, CFG_WING_ANGLE_MIN_DEG, CFG_WING_ANGLE_MAX_DEG);
  out[AERO_RF] = clampf(base + lat, CFG_WING_ANGLE_MIN_DEG, CFG_WING_ANGLE_MAX_DEG);
  out[AERO_LR] = clampf(base - lat, CFG_WING_ANGLE_MIN_DEG, CFG_WING_ANGLE_MAX_DEG);
  out[AERO_RR] = clampf(base + lat, CFG_WING_ANGLE_MIN_DEG, CFG_WING_ANGLE_MAX_DEG);
}

class ActiveAeroController {
 public:
  explicit ActiveAeroController(float lateral_gain = CFG_AERO_LATERAL_G_GAIN_DEG)
      : lateral_gain_(lateral_gain), rate_dps_(CFG_WING_RATE_MAX_DPS) {
    for (float &c : current_) c = CFG_WING_FAILSAFE_ANGLE_DEG;
  }

  /* rec may be nullptr (nothing received yet). */
  AeroOutput compute(const AeroInputs &in, const AiWingRecommendation *rec, uint32_t now_ms) {
    AeroOutput o;
    // FW 2.3: FAULT no longer parks the flaps — only E-STOP, shutdown, boot or aero mode 2.
    bool safe_override = in.state == VS_EMERGENCY_STOP || in.state == VS_SHUTDOWN || in.state < VS_IDLE ||
                         in.force_failsafe || in.mode == AERO_MODE_FAILSAFE_HOLD;
    if (safe_override) {
      for (int i = 0; i < 4; ++i) o.desired[i] = o.target[i] = current_[i] = CFG_WING_FAILSAFE_ANGLE_DEG;
      o.ai_reason = (rec && rec->valid) ? AI_REJ_SAFE_STATE : AI_NONE_RECEIVED;
      return o;  // no rate limit: failsafe is commanded immediately
    }
    if (in.baseline_override) {
      for (int i = 0; i < 4; ++i)
        o.desired[i] = clampf(finite(in.baseline[i]) ? in.baseline[i] : CFG_WING_FAILSAFE_ANGLE_DEG,
                              CFG_WING_ANGLE_MIN_DEG, CFG_WING_ANGLE_MAX_DEG);
    } else {
      aeroBaseline(in.speed_kmh, in.lat_g, lateral_gain_, o.desired);
    }

    if (rec == nullptr || !rec->valid) {
      o.ai_reason = AI_NONE_RECEIVED;
    } else if (in.mode != AERO_MODE_AI_ASSIST || !in.allow_ai) {
      o.ai_reason = AI_REJ_MODE_DISABLED;
    } else if (in.state == VS_FAULT) {
      o.ai_reason = AI_REJ_SAFE_STATE;   // the AI never acts during a fault; the flaps keep their baseline
    } else {
      o.ai_reason = aiRecommendationCheck(*rec, now_ms);
      if (o.ai_reason == AI_ACCEPTED) {
        const float ai[4] = {rec->lf, rec->rf, rec->lr, rec->rr};
        for (int i = 0; i < 4; ++i) {
          float delta = clampf(ai[i] - o.desired[i], -CFG_AI_MAX_DELTA_DEG, CFG_AI_MAX_DELTA_DEG);
          o.desired[i] = clampf(o.desired[i] + delta, CFG_WING_ANGLE_MIN_DEG, CFG_WING_ANGLE_MAX_DEG);
        }
        o.ai_applied = true;
      }
    }
    float dt = clampf(in.dt_s, 0.0f, 0.1f);
    for (int i = 0; i < 4; ++i) {
      current_[i] = clampf(slew(current_[i], o.desired[i], rate_dps_, dt),
                           CFG_WING_ANGLE_MIN_DEG, CFG_WING_ANGLE_MAX_DEG);
      o.target[i] = current_[i];
    }
    return o;
  }

 void set_rate_dps(float r) { if (finite(r) && r > 0) rate_dps_ = r; }
  float rate_dps() const { return rate_dps_; }

 private:
  float lateral_gain_;
  float rate_dps_;
  float current_[4];
};

// =============================================================================
// 7. SERVO CALIBRATION MATHS (MG996R + internal potentiometer feedback)
// =============================================================================
enum ServoId : uint8_t { SERVO_STEERING = 0, SERVO_LF = 1, SERVO_RF = 2, SERVO_LR = 3, SERVO_RR = 4, SERVO_COUNT = 5 };

struct ServoCal {
  float angle_min_deg;     // logical angle at pulse_min_us
  float angle_max_deg;     // logical angle at pulse_max_us
  uint16_t pulse_min_us;   // [PLACEHOLDER] bench-measure per servo
  uint16_t pulse_max_us;
  int32_t fb_raw_at_min;   // feedback ADC reading at angle_min_deg (from calibration)
  int32_t fb_raw_at_max;   // feedback ADC reading at angle_max_deg
  bool fb_calibrated;
};

inline uint16_t servoAngleToPulse(const ServoCal &c, float angle_deg) {
  float lo = c.angle_min_deg < c.angle_max_deg ? c.angle_min_deg : c.angle_max_deg;
  float hi = c.angle_min_deg < c.angle_max_deg ? c.angle_max_deg : c.angle_min_deg;
  float a = clampf(finite(angle_deg) ? angle_deg : 0.0f, lo, hi);
  float span = c.angle_max_deg - c.angle_min_deg;
  float t = (span == 0.0f) ? 0.5f : (a - c.angle_min_deg) / span;
  float us = c.pulse_min_us + t * (static_cast<float>(c.pulse_max_us) - c.pulse_min_us);
  return static_cast<uint16_t>(clampf(us + 0.5f, 500.0f, 2500.0f));
}

/* Two-point linear map raw -> angle. Returns NAN if not calibrated. */
inline float servoFeedbackToAngle(const ServoCal &c, int32_t raw) {
  if (!c.fb_calibrated || c.fb_raw_at_max == c.fb_raw_at_min) return NAN;
  float t = static_cast<float>(raw - c.fb_raw_at_min) / static_cast<float>(c.fb_raw_at_max - c.fb_raw_at_min);
  return c.angle_min_deg + t * (c.angle_max_deg - c.angle_min_deg);
}

/* Commanded-vs-measured error with persistence. The command passed in must be
 * the rate-limited setpoint (what the servo can physically follow). */
class PositionMonitor {
 public:
  bool update(float commanded, float measured, uint32_t now_ms) {
    bool cond = finite(measured) && std::fabs(commanded - measured) > CFG_SERVO_POS_ERR_MAX_DEG;
    return persist_.update(cond, now_ms, CFG_SERVO_POS_ERR_PERSIST_MS);
  }
 private:
  Persist persist_;
};

// =============================================================================
// 7b. SERVO TRIM (FW 2.3) — the live servo calibration: pulse at each end of travel,
//     steering centre, the steering->flap law and the knob. Defaults come from
//     vcu_calibration.h; CONFIG keys 30-45 change them live (dashboard / console).
//     Steering angles use the project convention: + = LEFT (map, IMU lat g, yaw).
// =============================================================================
struct ServoTrim {
  int32_t steer_left_us, steer_center_us, steer_right_us;
  int32_t flap_flat_us[4];        // FL, FR, RL, RR at 0 deg (least downforce)
  int32_t flap_max_us[4];         // ... at CFG_WING_ANGLE_MAX_DEG (most downforce)
  int32_t steer_lock_cdeg;        // road-wheel angle at full lock
  int32_t flap_neutral_cdeg;      // all flaps, wheels straight
  int32_t flap_swing_cdeg;        // outside +, inside - at full lock
  int32_t knob_cdeg_per_click;    // steering per knob detent
  int32_t knob_reverse;           // 1 = clockwise steers left
};

inline ServoTrim servoTrimDefaults() {
  ServoTrim t{};
  t.steer_left_us = VCU_CAL_STEER_LEFT_US; t.steer_center_us = VCU_CAL_STEER_CENTER_US;
  t.steer_right_us = VCU_CAL_STEER_RIGHT_US;
  const int32_t flat[4] = {VCU_CAL_FLAP_FL_FLAT_US, VCU_CAL_FLAP_FR_FLAT_US, VCU_CAL_FLAP_RL_FLAT_US, VCU_CAL_FLAP_RR_FLAT_US};
  const int32_t mx[4] = {VCU_CAL_FLAP_FL_MAX_US, VCU_CAL_FLAP_FR_MAX_US, VCU_CAL_FLAP_RL_MAX_US, VCU_CAL_FLAP_RR_MAX_US};
  for (int i = 0; i < 4; ++i) { t.flap_flat_us[i] = flat[i]; t.flap_max_us[i] = mx[i]; }
  t.steer_lock_cdeg = static_cast<int32_t>(VCU_CAL_STEER_LOCK_DEG * 100.0f + 0.5f);
  t.flap_neutral_cdeg = static_cast<int32_t>(VCU_CAL_FLAP_NEUTRAL_DEG * 100.0f + 0.5f);
  t.flap_swing_cdeg = static_cast<int32_t>(VCU_CAL_FLAP_SWING_DEG * 100.0f + 0.5f);
  t.knob_cdeg_per_click = static_cast<int32_t>(VCU_CAL_KNOB_DEG_PER_CLICK * 100.0f + 0.5f);
  t.knob_reverse = VCU_CAL_KNOB_REVERSE ? 1 : 0;
  return t;
}
/* Every field inside its legal range (used before trusting values loaded from NVS). */
inline bool servoTrimValid(const ServoTrim &t) {
  auto us = [](int32_t v) { return v >= 500 && v <= 2500; };
  if (!us(t.steer_left_us) || !us(t.steer_center_us) || !us(t.steer_right_us)) return false;
  for (int i = 0; i < 4; ++i) if (!us(t.flap_flat_us[i]) || !us(t.flap_max_us[i])) return false;
  return t.steer_lock_cdeg >= 500 && t.steer_lock_cdeg <= 4500 && t.flap_neutral_cdeg >= 0 &&
         t.flap_neutral_cdeg <= 4500 && t.flap_swing_cdeg >= 0 && t.flap_swing_cdeg <= 9000 &&
         t.knob_cdeg_per_click >= 50 && t.knob_cdeg_per_click <= 1000 && (t.knob_reverse == 0 || t.knob_reverse == 1);
}
/* FNV-1a over the FILE defaults: stored with every NVS save, so an edited vcu_calibration.h wins. */
inline uint32_t servoTrimFingerprint(const ServoTrim &t) {
  uint32_t h = 2166136261u;
  const uint8_t *p = reinterpret_cast<const uint8_t *>(&t);
  for (size_t i = 0; i < sizeof(ServoTrim); ++i) { h ^= p[i]; h *= 16777619u; }
  return h;
}
/* FW 2.3.3: fingerprint of the FLAP LAW + KNOB fields only (no pulses). */
inline uint32_t servoTrimLawFingerprint(const ServoTrim &t) {
  const int32_t f[5] = {t.steer_lock_cdeg, t.flap_neutral_cdeg, t.flap_swing_cdeg, t.knob_cdeg_per_click, t.knob_reverse};
  uint32_t h = 2166136261u;
  const uint8_t *p = reinterpret_cast<const uint8_t *>(f);
  for (size_t i = 0; i < sizeof(f); ++i) { h ^= p[i]; h *= 16777619u; }
  return h;
}
inline bool servoTrimPulsesEqual(const ServoTrim &a, const ServoTrim &b) {
  if (a.steer_left_us != b.steer_left_us || a.steer_center_us != b.steer_center_us || a.steer_right_us != b.steer_right_us) return false;
  for (int i = 0; i < 4; ++i) if (a.flap_flat_us[i] != b.flap_flat_us[i] || a.flap_max_us[i] != b.flap_max_us[i]) return false;
  return true;
}
/* FW 2.3.3 boot rule. Saved PULSES always win (a re-flash must never move a servo past the end
 * points set on the car). The flap law / knob fields come from the file when the file's law
 * changed since the save (law_fp_saved = what calSave stored), else from the save. */
inline ServoTrim servoTrimBoot(const ServoTrim &saved, const ServoTrim &file, uint32_t law_fp_saved, bool &law_from_file) {
  ServoTrim t = saved;
  law_from_file = law_fp_saved != servoTrimLawFingerprint(file);
  if (law_from_file) {
    t.steer_lock_cdeg = file.steer_lock_cdeg; t.flap_neutral_cdeg = file.flap_neutral_cdeg;
    t.flap_swing_cdeg = file.flap_swing_cdeg; t.knob_cdeg_per_click = file.knob_cdeg_per_click;
    t.knob_reverse = file.knob_reverse;
  }
  return t;
}
inline float steerLockDeg(const ServoTrim &t) { return clampf(t.steer_lock_cdeg / 100.0f, 1.0f, 45.0f); }

/* steering angle (+ = LEFT) -> pulse, piecewise through the centre pulse */
inline uint16_t steerPulseUs(const ServoTrim &t, float steer_deg) {
  float s = clampf((finite(steer_deg) ? steer_deg : 0.0f) / steerLockDeg(t), -1.0f, 1.0f);
  float us = s >= 0.0f ? t.steer_center_us + s * static_cast<float>(t.steer_left_us - t.steer_center_us)
                       : t.steer_center_us + (-s) * static_cast<float>(t.steer_right_us - t.steer_center_us);
  return static_cast<uint16_t>(clampf(us + 0.5f, 500.0f, 2500.0f));
}
/* flap angle 0..45 deg -> pulse (FLAT..MAX, either direction) */
inline uint16_t flapPulseUs(const ServoTrim &t, int flap, float deg) {
  if (flap < 0 || flap > 3) return 1500;
  float f = clampf((finite(deg) ? deg : 0.0f) / CFG_WING_ANGLE_MAX_DEG, 0.0f, 1.0f);
  float us = t.flap_flat_us[flap] + f * static_cast<float>(t.flap_max_us[flap] - t.flap_flat_us[flap]);
  return static_cast<uint16_t>(clampf(us + 0.5f, 500.0f, 2500.0f));
}
/* THE STEERING -> FLAP LAW (FW 2.3).  s = steering / lock, + = left, -1..1
 *   LEFT flaps  (LF, LR) = neutral - s * swing      turning RIGHT (s < 0): left flaps UP
 *   RIGHT flaps (RF, RR) = neutral + s * swing      turning LEFT  (s > 0): right flaps UP
 * i.e. the OUTSIDE pair gains downforce and the INSIDE pair loses it, in proportion to how
 * far the wheels are turned. Same sign convention as aeroBaseline() (+lat g raises the right). */
inline void steeringFlaps(const ServoTrim &t, float steer_deg, float out[4]) {
  float s = clampf((finite(steer_deg) ? steer_deg : 0.0f) / steerLockDeg(t), -1.0f, 1.0f);
  float n = t.flap_neutral_cdeg / 100.0f, w = t.flap_swing_cdeg / 100.0f;
  out[AERO_LF] = clampf(n - s * w, CFG_WING_ANGLE_MIN_DEG, CFG_WING_ANGLE_MAX_DEG);
  out[AERO_RF] = clampf(n + s * w, CFG_WING_ANGLE_MIN_DEG, CFG_WING_ANGLE_MAX_DEG);
  out[AERO_LR] = clampf(n - s * w, CFG_WING_ANGLE_MIN_DEG, CFG_WING_ANGLE_MAX_DEG);
  out[AERO_RR] = clampf(n + s * w, CFG_WING_ANGLE_MIN_DEG, CFG_WING_ANGLE_MAX_DEG);
}

// =============================================================================
// 8. DRIVER COMMAND, MOTOR & BTS7960 H-BRIDGE MAPPING
// =============================================================================
enum DriverFlags : uint8_t { DRV_FLAG_ARM = 1 << 0, DRV_FLAG_ESTOP = 1 << 1, DRV_FLAG_ESTOP_RESET = 1 << 2 };

struct DriverCommand {
  uint8_t sequence = 0;
  int16_t steering_permille = 0;  // -1000 (full left) .. +1000 (full right)
  int16_t throttle_permille = 0;  // -1000 (brake/reverse) .. +1000 (full forward)
  uint8_t flags = 0;
  uint32_t rx_ms = 0;
  bool valid = false;
};

inline bool driverCommandFresh(const DriverCommand &c, uint32_t now_ms) {
  return c.valid && ageMs(now_ms, c.rx_ms) <= CFG_DRIVER_CMD_TIMEOUT_MS;
}

/* BTS7960 (IBT-2) sign-magnitude drive using ONE LEDC channel:
 *   forward : RPWM = duty, LPWM = LOW
 *   reverse : RPWM = 1-|duty|, LPWM = HIGH   (M+ - M- averages to -|duty|)
 *   brake   : RPWM = LOW, LPWM = LOW, EN = HIGH (both low-side on)
 *   disable : EN = LOW (bridge high-impedance, motor coasts)          */
struct HBridgeOut { float rpwm_duty; bool lpwm_high; bool enable; };

inline HBridgeOut hbridgeMap(float signed_duty, bool enable) {
  HBridgeOut o{0.0f, false, enable};
  if (!enable || !finite(signed_duty)) { o.enable = false; return o; }
  float d = clampf(signed_duty, -1.0f, 1.0f);
  if (d >= 0.0f) { o.rpwm_duty = d; o.lpwm_high = false; }
  else { o.rpwm_duty = 1.0f + d; o.lpwm_high = true; }
  return o;
}

class MotorController {
 public:
  /* reverse_enabled = false for the Stage 2d L298N build: direction is strapped
   * at the driver, so negative throttle can only mean "coast" (duty 0). */
  explicit MotorController(bool reverse_enabled = CFG_MOTOR_REVERSE_ENABLED)
      : reverse_enabled_(reverse_enabled) {}
  /* Runtime limits (tunable keys 17 and 21). Clamped to sane ranges. */
  void set_limits(float max_duty, float current_limit_a) {
    if (finite(max_duty)) max_duty_ = clampf(max_duty, 0.05f, 1.0f);
    if (finite(current_limit_a)) current_limit_a_ = clampf(current_limit_a, 0.2f, CFG_BATTERY_OVERCURRENT_A);
  }
  float max_duty() const { return max_duty_; }
  float current_limit_a() const { return current_limit_a_; }

  /* Returns signed duty in [-1, 1]. `allowed` false => ramp is reset to 0. */
  float update(int16_t throttle_permille, bool allowed, float speed_kmh, float battery_v,
               float battery_current_a, float dt_s) {
    if (!allowed) { duty_ = 0.0f; braking_ = false; derating_ = false; return 0.0f; }
    float t = clampf(throttle_permille / 1000.0f, -1.0f, 1.0f);
    if (std::fabs(throttle_permille) < CFG_THROTTLE_NEUTRAL_PERMILLE) t = 0.0f;

    float max_fwd = max_duty_;
    derating_ = false;
    float cell_v = battery_v / CFG_BATTERY_CELLS;
    if (finite(cell_v) && cell_v < CFG_CELL_DERATE_V) {  // linear derate to 30% at undervolt
      float k = clampf((cell_v - CFG_CELL_UNDERVOLT_V) / (CFG_CELL_DERATE_V - CFG_CELL_UNDERVOLT_V), 0.0f, 1.0f);
      max_fwd *= 0.3f + 0.7f * k;
    }
    if (finite(battery_current_a) && std::fabs(battery_current_a) > current_limit_a_) {
      float over = std::fabs(battery_current_a) / current_limit_a_;  // > 1
      max_fwd = clampf(max_fwd / over, 0.1f, max_fwd);
      derating_ = true;
    }

    float target;
    braking_ = false;
    if (t >= 0.0f) {
      target = t * max_fwd;
    } else if (!reverse_enabled_) {
      target = 0.0f;  // forward-only driver: negative throttle = coast (no active brake exists)
      braking_ = finite(speed_kmh) && speed_kmh > CFG_MOTOR_REVERSE_ENTRY_KMH;
    } else if (finite(speed_kmh) && speed_kmh <= CFG_MOTOR_REVERSE_ENTRY_KMH) {
      target = t * CFG_MOTOR_REVERSE_MAX_DUTY;
    } else {
      target = 0.0f;  // negative throttle while rolling = brake
      braking_ = true;
    }
    if (braking_) duty_ = 0.0f;  // brake immediately, no ramp
    else duty_ = slew(duty_, target, CFG_MOTOR_RAMP_PER_S, clampf(dt_s, 0.0f, 0.1f));
    return duty_;
  }
  bool braking() const { return braking_; }
  bool derating() const { return derating_; }
  float duty() const { return duty_; }

 private:
  bool reverse_enabled_;
  float max_duty_ = CFG_MOTOR_MAX_DUTY;
  float current_limit_a_ = CFG_MOTOR_CURRENT_LIMIT_A;
  float duty_ = 0.0f;
  bool braking_ = false;
  bool derating_ = false;
};

/* L298N with IN1/IN3 strapped high and IN2/IN4 strapped low: the ONLY signal is
 * ENA+ENB PWM. Negative duty cannot be expressed, so it maps to 0 (coast). */
inline float l298nDuty(float signed_duty, bool enable) {
  if (!enable || !finite(signed_duty) || signed_duty <= 0.0f) return 0.0f;
  return clampf(signed_duty, 0.0f, 1.0f);
}

