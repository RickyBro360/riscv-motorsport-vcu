class VcuController {
 public:
  ConfigStore cfg;                         // the ONLY live copy of the tunables (the sketch mirrors it)
  static constexpr uint32_t PREVIEW_MS = 2500;

  /* reverse_enabled false for both builds (forward-only drivers). kill_switch: PCB rev B. */
  void begin(uint8_t hw_profile, bool kill_switch_fitted, bool encoder_fitted) {
    cfg.hw_profile = hw_profile; kill_switch_ = kill_switch_fitted; encoder_ = encoder_fitted;
  }
  bool kill_switch_fitted() const { return kill_switch_; }
  bool encoder_fitted() const { return encoder_; }
  /* FW 2.3.4: wheel speed from the duty model instead of the wheel sensors (stall watchdog off: it needs pulses). */
  void set_speed_from_duty(bool on, bool report = true) { speed_model_on_ = on; cfg.speed_source = on && report ? 1 : 0; }

  /* Power-on: BOOT -> INIT -> SELF_TEST -> IDLE. FW 2.3: a failed self-test item is a WARNING
   * (reported in the fault flags and on the console), the car still goes to IDLE. */
  void boot(uint32_t self_test_mask) {
    sup_.event(VE_BOOT_DONE);
    sup_.event(VE_INIT_DONE);
    self_test_done(self_test_mask);
  }
  /* After an e-stop reset the state machine is back in INIT; step() asks for a self-test. */
  void self_test_done(uint32_t mask) {
    if (sup_.state() == VS_INIT) sup_.event(VE_INIT_DONE);
    self_test_mask_ = mask;
    sup_.event(VE_SELF_TEST_PASS);         // FW 2.3: never parks the car in FAULT (mask -> warning bit)
  }
  VehicleState state() const { return sup_.state(); }
  uint32_t self_test_mask() const { return self_test_mask_; }
  uint8_t run_state() const { return run_state_; }
  uint8_t bench_type() const { return bench_type_; }
  bool bench_remote() const { return bench_remote_; }
  int32_t knob_pos() const { return knob_pos_; }

  /* Every CONFIG_WRITE (CAN 0x180 or the console `set`) comes here, in the control task.
   * Commands (run, e-stop, motor, knob, calibration) are decided against the live state; the rest
   * goes to the store. */
  ConfigStatus write(uint8_t key, int32_t value, bool from_console, uint32_t now_ms, int32_t &value_out) {
    value_out = value;
    if (key == CFG_KEY_ESTOP) {
      if (value == ESTOP_CMD_TRIGGER) { estop_cmd_ = true; return CFG_APPLIED; }
      if (value == ESTOP_CMD_RESET) { reset_cmd_ = true; return CFG_APPLIED; }
      return CFG_REJ_RANGE;
    }
    if (key == CFG_KEY_RUN_CMD) {
      if (value == RUN_CMD_STOP) { request_run(RUN_OFF, 0, 0, !from_console, now_ms); return CFG_APPLIED; }
      if (value == RUN_CMD_LAPS) return request_run(RUN_BENCH_LAPS, 0, cfg.snap.run_laps, !from_console, now_ms);
      if (value == RUN_CMD_DYNO_CAL) return request_run(RUN_DYNO_CAL, 0, 0, !from_console, now_ms);
      return CFG_REJ_RANGE;
    }
    if (key == CFG_KEY_MOTOR_CMD) return motor_command(value, !from_console, now_ms, value_out);
    if (key == CFG_KEY_KNOB_CMD) {
      if (value != 1) return CFG_REJ_RANGE;
      knob_pos_ = 0; events_ |= EV_KNOB; return CFG_APPLIED;
    }
    if (key == CFG_KEY_AI_STEER_CMD) {          // FW 2.3.12
      if (value < -900 || value > 900) return CFG_REJ_RANGE;
      if (sup_.state() == VS_FAULT || sup_.state() == VS_EMERGENCY_STOP) { ai_steer_on_ = false; return CFG_REJ_STATE; }
      if (!from_console && !ground_ok_) return CFG_REJ_STATE;
      if (ai_steer_block_until_ms_ != 0 && static_cast<int32_t>(now_ms - ai_steer_block_until_ms_) < 0) return CFG_REJ_STATE;  // knob just turned
      ai_steer_block_until_ms_ = 0;
      const float lock_deg = clampf(cfg.trim.steer_lock_cdeg / 100.0f, 5.0f, 45.0f);
      ai_steer_deg_ = clampf(value / 10.0f, -lock_deg, lock_deg);
      ai_steer_on_ = true; ai_steer_remote_ = !from_console; ai_steer_ms_ = now_ms;
      value_out = static_cast<int32_t>(ai_steer_deg_ * 10.0f + (ai_steer_deg_ >= 0 ? 0.5f : -0.5f));
      return CFG_APPLIED;
    }
    if (key == CFG_KEY_DRS_CMD) {     // FW 2.3.3 DRS: works in any live state (IDLE, ARMED, DRIVE, FAULT, runs)
      if (value == 0) { drs_on_ = false; return CFG_APPLIED; }
      if (value != 1) return CFG_REJ_RANGE;
      const VehicleState st = sup_.state();
      if (st < VS_IDLE || st == VS_EMERGENCY_STOP || st == VS_SHUTDOWN) return CFG_REJ_STATE;
      drs_on_ = true; drs_start_ms_ = now_ms;   // pressing again restarts the 5 s
      return CFG_APPLIED;
    }
    if (key == CFG_KEY_DEMO_CMD) {    // FW 2.3.4: same conditions as the dashboard motor (IDLE, no fault, link)
      if (value == 0) {
        if (bench_type_ == RUN_DEMO || (demo_lap_ && bench_type_ == RUN_BENCH_LAPS)) { stop_bench(); events_ |= EV_RUN_STOPPED; }
        return CFG_APPLIED;
      }
      // FW 2.3.10 demo 2 on any circuit: 2 = the circuit selected now, 100 + id = that circuit
      if (value == 2 || (value >= 100 && value < 100 + TRACK_COUNT)) {
        if (demo_lap_ && bench_type_ == RUN_BENCH_LAPS) return CFG_APPLIED;
        if (sup_.state() != VS_IDLE || bench_type_ != RUN_OFF) return CFG_REJ_STATE;
        const uint8_t prev_mode = cfg.snap.drive_mode, prev_track = cfg.snap.track_id;
        const int32_t prev_len = cfg.snap.lap_length_cm;
        cfg.snap.drive_mode = DRIVE_MODE_DYNO;          // the map run needs it; restored when the lap ends
        if (value >= 100) cfg.snap.track_id = static_cast<uint8_t>(value - 100);
        if (cfg.snap.track_id >= TRACK_COUNT) cfg.snap.track_id = TRACK_DEFAULT_ID;
        cfg.snap.lap_length_cm = demoLapLengthCm(cfg.snap.track_id, cfg.active, demo_vmax_kmh(), VCU_CAL_DEMO_LAP_SECONDS);
        // full lock from 3 deg of map steering on a fast circuit, up to 35 % of the circuit's tightest corner
        demo_tight_deg_ = std::max(3.0f, 0.35f * trackMaxSteerDeg(cfg.snap.track_id, cfg.active));
        const ConfigStatus r = request_run(RUN_BENCH_LAPS, 0, 1, !from_console, now_ms);
        if (r == CFG_APPLIED) { demo_lap_ = true; demo_prev_mode_ = prev_mode; }
        else { cfg.snap.drive_mode = prev_mode; cfg.snap.track_id = prev_track; cfg.snap.lap_length_cm = prev_len; }
        return r;
      }
      if (value != 1) return CFG_REJ_RANGE;
      if (bench_type_ == RUN_DEMO) return CFG_APPLIED;
      const ConfigStatus r = request_run(RUN_DEMO, 0, 0, !from_console, now_ms);
      if (r == CFG_APPLIED) { demo_drs_fired_ = false; knob_pos_ = 0; }
      return r;
    }
    if (key == CFG_KEY_CAL_CMD) {
      if (value == CAL_CMD_SAVE) { events_ |= EV_CAL_SAVE; return CFG_APPLIED; }          // the sketch writes NVS
      if (value == CAL_CMD_REVERT) { cfg.trim = servoTrimDefaults(); events_ |= EV_CAL_REVERTED; return CFG_APPLIED; }
      return CFG_REJ_RANGE;
    }
    ConfigContext ctx;
    ctx.in_drive = sup_.state() == VS_DRIVE;
    ctx.lap_running = run_state_ == RUN_TRACK_DRIVE || run_state_ == RUN_BENCH_LAPS;
    ctx.run_active = run_state_ != RUN_OFF || bench_type_ != RUN_OFF;
    uint8_t mode_before = cfg.snap.drive_mode;
    ConfigStatus r = cfg.write(key, value, ctx, value_out);
    if (cfg.snap.drive_mode != mode_before) mode_changed_ = true;
    // A pulse key moves THAT servo to the new pulse for PREVIEW_MS so it can be seen on the car
    // (not while the circuit map is steering).
    if (r == CFG_APPLIED && configKeyIsServoPulse(key) && !ctx.lap_running) {
      preview_key_ = key; preview_us_ = static_cast<uint16_t>(value); preview_start_ms_ = now_ms; preview_on_ = true;
    }
    return r;
  }

  /* FW 2.3 — motor from the dashboard (key 9) or console `motor`. duty_permille 0 = stop. */
  ConfigStatus motor_command(int32_t duty_permille, bool remote, uint32_t now_ms, int32_t &value_out) {
    value_out = duty_permille;
    if (duty_permille < 0 || duty_permille > 1000) return CFG_REJ_RANGE;
    if (duty_permille == 0) {
      if (bench_type_ == RUN_BENCH_MOTOR || bench_type_ == RUN_DEMO) { stop_bench(); events_ |= EV_RUN_STOPPED; }
      return CFG_APPLIED;
    }
    const float duty = duty_permille / 1000.0f;
    if (bench_type_ == RUN_BENCH_MOTOR) {                 // already running: change the duty, keep running
      if (remote && !ground_ok_) return CFG_REJ_STATE;
      bench_duty_ = duty; bench_remote_ = bench_remote_ || remote; events_ |= EV_MOTOR_DUTY;
      return CFG_APPLIED;
    }
    return request_run(RUN_BENCH_MOTOR, duty, 0, remote, now_ms);
  }

  /* Start/stop a bench run. type RUN_OFF = stop. remote = from the dashboard (the ground link
   * is then the deadman). Circuit runs and dyno cal need DYNO mode; the plain motor run (FW 2.3)
   * works in either mode. All need IDLE (not FAULT / E-STOP) and, if remote, a live link. */
  ConfigStatus request_run(uint8_t type, float duty, uint16_t laps, bool remote, uint32_t now_ms) {
    if (type == RUN_OFF) {
      if (bench_type_ != RUN_OFF) { stop_bench(); events_ |= EV_RUN_STOPPED; }
      if (remote) cfg.snap.track_run = false;          // the dashboard's Stop also ends a map-following DRIVE
      return CFG_APPLIED;
    }
    if (bench_type_ == type && remote && bench_remote_ && type != RUN_BENCH_MOTOR) return CFG_APPLIED;  // resent: idempotent
    if (type != RUN_BENCH_MOTOR && type != RUN_DEMO && cfg.snap.drive_mode != DRIVE_MODE_DYNO) return CFG_REJ_STATE;   // map runs: rollers only
    if (sup_.state() != VS_IDLE || !last_permits_drive_ || run_state_ == RUN_TRACK_DRIVE) return CFG_REJ_STATE;
    if (bench_type_ != RUN_OFF) return CFG_REJ_STATE;                  // stop the current run first
    if (remote && !ground_ok_) return CFG_REJ_STATE;
    bench_type_ = type; bench_duty_ = clampf(duty, 0.0f, 1.0f); bench_laps_ = laps; bench_start_ms_ = now_ms;
    bench_remote_ = remote; stall_lockout_ = false;
    if (type == RUN_DYNO_CAL) dyno_.begin(cfg.active.duty_cap_permille / 1000.0f, now_ms);
    events_ |= EV_RUN_STARTED;
    return CFG_APPLIED;
  }

  VcuOutputs step(const VcuInputs &in_raw) {
    VcuOutputs o;
    VcuInputs in = in_raw;
    if (speed_model_on_) {            // FW 2.3.4: rear speed from the duty model; the fronts are not driven
      const float v = speed_model_.v_kmh;
      in.wheel_kmh[0] = in.wheel_kmh[1] = 0.0f; in.wheel_kmh[2] = in.wheel_kmh[3] = v; in.speed_kmh = v;
      in.rear_dist_m = v / 3.6f * clampf(finite(in.dt_s) ? in.dt_s : 0.01f, 0.0f, 0.1f);
    }
    const uint32_t now = in.now_ms;
    const float dt = clampf(finite(in.dt_s) ? in.dt_s : 0.01f, 0.0f, 0.1f);
    const AeroMode mode = static_cast<AeroMode>(cfg.snap.aero_mode);
    const bool dyno_mode = cfg.snap.drive_mode == DRIVE_MODE_DYNO;
    const ServoTrim &trim = cfg.trim;
    const float lock = steerLockDeg(trim);
    motor_.set_limits(cfg.active.duty_cap_permille / 1000.0f, cfg.active.current_limit_ca / 100.0f);
    aero_.set_rate_dps(static_cast<float>(cfg.active.wing_slew_dps));
    const bool rear_pulse = in.rear_pulses > 0;
    ground_ok_ = in.hb_seen && in.hb_age_ms < CFG_REMOTE_LINK_TIMEOUT_MS && in.hb.lora_link_ok;

    o.request_self_test = sup_.state() == VS_INIT;
    const bool driver_fresh = driverCommandFresh(in.driver, now);
    const bool arm = driver_fresh && (in.driver.flags & DRV_FLAG_ARM);

    // --- servo position monitors (paused while a bench override / calibration preview moves servos) ---
    float fb[SERVO_COUNT];
    for (int i = 0; i < SERVO_COUNT; ++i) fb[i] = (in.bench_override || preview_on_) ? NAN : in.fb_deg[i];
    const bool steer_err = pos_mon_[SERVO_STEERING].update(steering_cmd_, fb[SERVO_STEERING], now);
    bool aero_err = false;
    for (int i = 0; i < 4; ++i) aero_err |= pos_mon_[SERVO_LF + i].update(aero_prev_[i], fb[SERVO_LF + i], now);

    // --- safety ---
    SafetyInputs si;
    si.now_ms = now; si.state = sup_.state(); si.watchdog_ok = in.watchdog_ok;
    si.imu_age_ms = in.imu_age_ms; si.power_age_ms = in.power_age_ms; si.temp_age_ms = in.temp_age_ms;
    si.power_sensor_present = in.power_sensor_present; si.temp_sensors_present = in.temp_sensors_present;
    si.battery_voltage_v = in.battery_v; si.battery_current_a = in.battery_a;
    si.battery_temp_c = finite(in.battery_temp_c) ? in.battery_temp_c : 25.0f;
    si.motor_temp_available = finite(in.motor_temp_c);
    si.motor_temp_c = si.motor_temp_available ? in.motor_temp_c : 25.0f;
    si.any_non_finite = !finite(in.accel_g[0]) || !finite(in.accel_g[1]) || !finite(in.accel_g[2]) ||
                        !finite(in.battery_v) || !finite(in.battery_a);
    si.can_link_ok = in.can_link_ok;
    si.lora_link_ok = !in.hb_seen || in.hb.lora_link_ok;
    si.steering_pos_error = steer_err; si.aero_pos_error = aero_err;
    si.driver_link_ok = driver_fresh;
    si.self_test_failed = self_test_mask_ != 0;
    si.ai_last_rejected = last_ai_reason_ != AI_ACCEPTED && last_ai_reason_ != AI_NONE_RECEIVED;
    si.motor_stall = static_cast<int32_t>(stall_flag_until_ - now) > 0;
    SafetyResult sr = safety_.evaluate(si);
    if (static_cast<int32_t>(remote_loss_until_ - now) > 0) {      // a dashboard run lost its link
      sr.fault_flags |= FAULT_BIT_COMM_LOSS;
      if (sr.worst < SEV_WARNING) sr.worst = SEV_WARNING;
    }

    // --- state machine ---
    SupervisorInputs sup_in;
    sup_in.now_ms = now; sup_in.safety = sr; sup_in.driver_fresh = driver_fresh; sup_in.arm_requested = arm;
    sup_in.estop_requested = (driver_fresh && (in.driver.flags & DRV_FLAG_ESTOP)) || in.estop_local || estop_cmd_;
    sup_in.estop_reset_requested = (driver_fresh && (in.driver.flags & DRV_FLAG_ESTOP_RESET)) || in.estop_reset_local || reset_cmd_;
    sup_in.throttle_permille = driver_fresh ? in.driver.throttle_permille : 0;
    estop_cmd_ = reset_cmd_ = false;
    const VehicleState st = sup_.step(sup_in);
    const bool actuate = stateAllowsActuation(st);
    const bool servos_live = st >= VS_IDLE && st <= VS_FAULT;      // IDLE, ARMED, DRIVE, FAULT
    last_permits_drive_ = sr.permits_drive;

    // --- bench / dashboard runs: end them on a FAULT, e-stop, ARM, mode change or lost link ---
    const bool bench_allowed = st == VS_IDLE && sr.permits_drive && (dyno_mode || bench_type_ == RUN_BENCH_MOTOR || bench_type_ == RUN_DEMO);
    if (bench_type_ != RUN_OFF && !bench_allowed) { stop_bench(); events_ |= EV_RUN_ABORT_FAULT; }
    if (bench_type_ != RUN_OFF && bench_remote_ && !ground_ok_) {
      stop_bench(); events_ |= EV_RUN_ABORT_LINK; remote_loss_until_ = now + CFG_REMOTE_LINK_FAULT_HOLD_MS;
    }
    if (bench_type_ == RUN_BENCH_MOTOR && !bench_remote_ && now - bench_start_ms_ > CFG_CONSOLE_MOTOR_TIMEOUT_MS) {
      stop_bench(); events_ |= EV_RUN_MOTOR_TIMEOUT;
    }
    if (!dyno_mode) cfg.snap.track_run = false;

    if (demo_lap_ && bench_type_ != RUN_BENCH_LAPS) {     // FW 2.3.8: demo lap over -> back to the mode it started in
      demo_lap_ = false; cfg.snap.drive_mode = demo_prev_mode_;
    }
    // --- run state ---
    uint8_t new_run = RUN_OFF;
    if (st == VS_DRIVE && cfg.snap.track_run && dyno_mode) new_run = RUN_TRACK_DRIVE;
    else if (bench_type_ != RUN_OFF) new_run = bench_type_;
    const bool was_lapping = run_state_ == RUN_TRACK_DRIVE || run_state_ == RUN_BENCH_LAPS;
    const bool lapping = new_run == RUN_TRACK_DRIVE || new_run == RUN_BENCH_LAPS;
    if (lapping && !was_lapping) { track_.start(cfg.snap.track_id, cfg.snap.lap_length_cm / 100.0f, now); events_ |= EV_TRACK_START; }
    if (!lapping && was_lapping) track_.stop();
    run_state_ = new_run;

    track_.advance(in.rear_dist_m, now);
    const bool lap_event = track_.lap_completed_event;
    if (lap_event) {
      events_ |= EV_LAP;
      if (cfg.commitAtLapBoundary()) lap_committed_ = true;
      if (run_state_ == RUN_BENCH_LAPS && bench_laps_ && track_.lap >= bench_laps_) { stop_bench(); events_ |= EV_RUN_LAPS_DONE; }
    }
    TrackSample smp;
    TrackCommand tcmd;
    if (lapping) tcmd = track_.command(cfg.active, now, &smp);
    if (lapping && demo_lap_) {       // FW 2.3.9: demo-lap shaping (speed + steering); flaps stay the map's
      tcmd.duty = demoLapDuty(smp.speed_frac, cfg.active);
      const float lk = steerLockDeg(cfg.trim);
      float tgt = demoLapSteerTarget(cfg.snap.track_id, track_.fraction(), cfg.active, lk, demo_tight_deg_);
      // each side of a chicane is held at full lock for 0.9 s so the wheels really get there; the other
      // side waits its turn (pending) instead of being skipped
      const bool tight = std::fabs(tgt) >= lk - 0.01f;
      const bool holding = demo_hold_ != 0.0f && now - demo_hold_ms_ < 900;
      if (holding) {
        if (tight && (tgt > 0) != (demo_hold_ > 0)) demo_pending_ = tgt;
        tgt = demo_hold_;
      } else if (demo_pending_ != 0.0f) {
        demo_hold_ = demo_pending_; demo_pending_ = 0; demo_hold_ms_ = now; tgt = demo_hold_;
      } else if (tight) {
        demo_hold_ = tgt; demo_hold_ms_ = now;
      } else demo_hold_ = 0;
      demo_steer_ += (tgt - demo_steer_) * clampf(dt / 0.2f, 0.0f, 1.0f);
      tcmd.steer_deg = demo_steer_;
    } else { demo_steer_ = 0; demo_hold_ = 0; demo_pending_ = 0; }

    // --- demo corner sequence (FW 2.3.4) ---
    DemoCmd dcmd;
    const bool demo = run_state_ == RUN_DEMO;
    if (demo) {
      const float dcap = cfg.active.duty_cap_permille / 1000.0f;
      const float top = std::min(dcap, VCU_CAL_DEMO_TOP_DUTY_PCT / 100.0f);
      const float lo = std::min(top, (VCU_CAL_MOTOR_MIN_DUTY_PCT + 2) / 100.0f);
      dcmd = demoSequence(now - bench_start_ms_, lo, top);
      bench_duty_ = dcmd.duty;
      if (dcmd.drs && !demo_drs_fired_) { demo_drs_fired_ = true; drs_on_ = true; drs_start_ms_ = now; }
      if (dcmd.done) { stop_bench(); events_ |= EV_RUN_STOPPED; }
    }

    // --- knob = steering wheel (FW 2.3) ---
    if (encoder_ && in.knob_detents) {
      const float step_deg = clampf(trim.knob_cdeg_per_click / 100.0f, 0.5f, 10.0f);
      const int32_t max_clicks = static_cast<int32_t>(std::ceil(lock / step_deg));
      knob_pos_ = std::max<int32_t>(-max_clicks, std::min<int32_t>(max_clicks, knob_pos_ + in.knob_detents));
      events_ |= EV_KNOB;
      // FW 2.3.12: a hand on the knob takes the steering back from the AI and keeps it for a while
      ai_steer_on_ = false; ai_steer_block_until_ms_ = now + CFG_AI_STEER_KNOB_HOLD_MS;
      if (ai_steer_block_until_ms_ == 0) ai_steer_block_until_ms_ = 1;
    }
    // FW 2.3.12: AI steering ends when its commands stop, the link drops, or the car faults / e-stops
    if (ai_steer_on_ && (static_cast<uint32_t>(now - ai_steer_ms_) > CFG_AI_STEER_TIMEOUT_MS ||
                         (ai_steer_remote_ && !ground_ok_) || sup_.state() == VS_FAULT || sup_.state() == VS_EMERGENCY_STOP))
      ai_steer_on_ = false;
    // clockwise = RIGHT = negative in the + = LEFT convention (knob_reverse flips it)
    const float knob_deg = clampf(-knob_pos_ * (trim.knob_cdeg_per_click / 100.0f) * (trim.knob_reverse ? -1.0f : 1.0f),
                                  -lock, lock);

    // --- steering: the circuit map in a run; a driver holding ARM in drive_client.py steers with their
    //     wheel; otherwise (IDLE, FAULT, dashboard motor runs, no driver) the KNOB is the steering wheel ---
    float steer_target = CFG_STEERING_FAILSAFE_DEG;
    uint8_t src = STEER_SRC_FAILSAFE;
    if (demo) {
      steer_target = clampf(dcmd.steer_frac * lock, -lock, lock); src = STEER_SRC_MAP;
    } else if (lapping && (actuate || run_state_ == RUN_BENCH_LAPS)) {
      steer_target = clampf(tcmd.steer_deg, -lock, lock); src = STEER_SRC_MAP;
    } else if (actuate && driver_fresh) {     // driver packet + = RIGHT; project convention + = LEFT
      steer_target = clampf(-in.driver.steering_permille / 1000.0f * lock, -lock, lock); src = STEER_SRC_DRIVER;
    } else if (servos_live && ai_steer_on_) {  // FW 2.3.12: the AI page steers (dashboard motor runs, IDLE)
      steer_target = clampf(ai_steer_deg_, -lock, lock); src = STEER_SRC_AI;
    } else if (servos_live && encoder_) {
      steer_target = knob_deg; src = STEER_SRC_KNOB;
    }
    steering_cmd_ = !servos_live ? CFG_STEERING_FAILSAFE_DEG
                                 : slew(steering_cmd_, steer_target, CFG_STEERING_RATE_MAX_DPS, dt);

    // --- motor ---
    const float cap = cfg.active.duty_cap_permille / 1000.0f;
    int16_t thr = sup_in.throttle_permille;
    bool motor_ok = false;
    switch (run_state_) {
      case RUN_TRACK_DRIVE: {   // the map sets the duty; the driver's throttle is a CEILING
        int16_t prof = static_cast<int16_t>(clampf(tcmd.duty / cap * 1000.0f, 0, 1000));
        thr = std::min<int16_t>(thr > 0 ? thr : 0, prof);
        motor_ok = stateAllowsMotor(st) && sr.permits_drive && driver_fresh;
        break;
      }
      case RUN_BENCH_LAPS:
        thr = static_cast<int16_t>(clampf(tcmd.duty / cap * 1000.0f, 0, 1000)); motor_ok = bench_allowed; break;
      case RUN_DEMO:
      case RUN_BENCH_MOTOR:
        thr = static_cast<int16_t>(clampf(bench_duty_ / cap * 1000.0f, 0, 1000)); motor_ok = bench_allowed; break;
      case RUN_DYNO_CAL: {
        float rear = (in.wheel_kmh[2] + in.wheel_kmh[3]) * 0.5f;
        float d = dyno_.update(rear, now);
        thr = static_cast<int16_t>(clampf(d / cap * 1000.0f, 0, 1000)); motor_ok = bench_allowed && dyno_.active();
        if (!dyno_.active()) {
          if (dyno_.phase == DynoCalibrator::DONE) {
            cfg.dyno_vmax_ckmh = static_cast<int32_t>(dyno_.vmax_kmh * 100.0f + 0.5f);
            cfg.dyno_start_permille = static_cast<int32_t>(dyno_.start_duty * 1000.0f + 0.5f);
            o.dyno_start_duty = dyno_.start_duty; o.dyno_vmax_kmh = dyno_.vmax_kmh;
            events_ |= EV_DYNO_DONE;
          } else {
            events_ |= EV_DYNO_FAILED;
          }
          bench_type_ = RUN_OFF; bench_remote_ = false;
        }
        break;
      }
      default:
        motor_ok = stateAllowsMotor(st) && sr.permits_drive && driver_fresh;
        break;
    }
    if (stall_lockout_) {    // after a stall: off until the run is restarted / the driver lets go
      if (run_state_ == RUN_OFF && (st != VS_DRIVE || std::abs(sup_in.throttle_permille) < CFG_THROTTLE_NEUTRAL_PERMILLE))
        stall_lockout_ = false;
      else motor_ok = false;
    }
    const float duty = motor_.update(thr, motor_ok, in.speed_kmh, in.battery_v, in.battery_a, dt);
    // traction control: track mode, the driver in DRIVE, no circuit run
    const bool tc_enabled = !dyno_mode && st == VS_DRIVE && run_state_ == RUN_OFF && cfg.snap.tc_slip_permille > 0;
    const float front = (in.wheel_kmh[0] + in.wheel_kmh[1]) * 0.5f, rear = (in.wheel_kmh[2] + in.wheel_kmh[3]) * 0.5f;
    const float tc_mult = tc_.update(tc_enabled, front, rear, cfg.snap.tc_slip_permille, dt, now);
    const float out_duty = (motor_ok && finite(duty) && duty > 0.0f) ? clampf(duty * tc_mult, 0.0f, 1.0f) : 0.0f;
    if (speed_model_on_) speed_model_.update(out_duty, dt);
    const bool stall_watch = !speed_model_on_ && ((run_state_ != RUN_OFF && run_state_ != RUN_DYNO_CAL) || st == VS_DRIVE);
    if (!stall_watch) {
      stall_.update(0.0f, true, now);                    // keep the timer fresh while not watching
    } else if (stall_.update(out_duty, rear_pulse, now)) {
      stall_lockout_ = true; stall_flag_until_ = now + 5000;
      if (bench_type_ != RUN_OFF) stop_bench();
      if (run_state_ == RUN_TRACK_DRIVE) cfg.snap.track_run = false;
      events_ |= EV_STALL;
    }

    // --- kill switch (PCB rev B BTS7004): 12 V to the bridges only while the motor may run ---
    const bool motor_phase = st == VS_ARMED || st == VS_DRIVE || bench_type_ != RUN_OFF;
    o.motor_power = kill_switch_ && motor_phase && sr.permits_drive && !stall_lockout_;

    // --- DRS (FW 2.3.3): FLAT for VCU_CAL_DRS_OPEN_MS, MAX for VCU_CAL_DRS_HOLD_MS, then the law ---
    uint8_t drs = 0;
    if (drs_on_ && !servos_live) drs_on_ = false;               // E-STOP / boot cancels it
    if (drs_on_) {
      const uint32_t el = now - drs_start_ms_;
      if (el < static_cast<uint32_t>(VCU_CAL_DRS_OPEN_MS)) drs = 1;
      else if (el < static_cast<uint32_t>(VCU_CAL_DRS_OPEN_MS + VCU_CAL_DRS_HOLD_MS)) drs = 2;
      else drs_on_ = false;
    }
    if (drs != drs_phase_) {
      events_ |= drs == 1 ? EV_DRS_OPEN : drs == 2 ? EV_DRS_HOLD : EV_DRS_END;
      drs_phase_ = drs;
    }

    // --- active aero: the map in a circuit run (AI may nudge it), else the STEERING (FW 2.3) ---
    AeroInputs ai_in;
    ai_in.speed_kmh = in.speed_kmh; ai_in.lat_g = in.accel_g[1]; ai_in.state = st; ai_in.mode = mode;
    ai_in.force_failsafe = sr.aero_failsafe; ai_in.dt_s = dt;
    ai_in.baseline_override = true;
    bool straight_now = false;
    if (lapping) {
      std::memcpy(ai_in.baseline, tcmd.flaps, sizeof(tcmd.flaps));
      straight_now = tcmd.straight_front;
      ai_in.allow_ai = true;
    } else {
      steeringFlaps(trim, steering_cmd_, ai_in.baseline);
      ai_in.allow_ai = false;
    }
    if (drs) {                                                  // DRS overrides the map and the steering law
      for (int i = 0; i < 4; ++i) ai_in.baseline[i] = drs == 1 ? CFG_WING_ANGLE_MIN_DEG : CFG_WING_ANGLE_MAX_DEG;
      ai_in.allow_ai = false;
      straight_now = drs == 1;
    }
    const AeroOutput ao = aero_.compute(ai_in, in.ai.valid ? &in.ai : nullptr, now);
    std::memcpy(aero_prev_, ao.target, sizeof(aero_prev_));
    const bool new_rec = in.ai.valid && in.ai.timestamp_ms != last_ai_ts_seen_;
    if (new_rec) { last_ai_ts_seen_ = in.ai.timestamp_ms; last_ai_reason_ = ao.ai_reason; }

    // --- calibration preview (a pulse key was just written) ---
    if (preview_on_ && (now - preview_start_ms_ >= PREVIEW_MS || lapping || st == VS_EMERGENCY_STOP)) preview_on_ = false;
    if (preview_on_) {
      o.preview_servo = static_cast<int8_t>(servoOfPulseKey(preview_key_));
      o.preview_us = preview_us_; o.preview_key = preview_key_; o.preview_elapsed_ms = now - preview_start_ms_;
    }

    // --- outputs ---
    uint8_t tflags = 0;
    if (lapping) {
      tflags |= TF_RUN_ACTIVE;
      if (smp.braking) tflags |= TF_BRAKING_ZONE;
      tflags |= (smp.sector & 0x03) << TF_SECTOR_SHIFT;
    }
    if (straight_now) tflags |= TF_STRAIGHT_MODE;
    if (run_state_ == RUN_BENCH_LAPS) tflags |= TF_BENCH_RUN;
    if (cfg.pending) tflags |= TF_CONFIG_PENDING;
    if (static_cast<int32_t>(stall_flag_until_ - now) > 0) tflags |= TF_STALLED;

    cfg.active_run_cmd = bench_type_ == RUN_BENCH_LAPS ? RUN_CMD_LAPS : bench_type_ == RUN_DYNO_CAL ? RUN_CMD_DYNO_CAL
                                                                                                    : RUN_CMD_STOP;
    cfg.demo_active = bench_type_ == RUN_DEMO ? 1 : (demo_lap_ && bench_type_ == RUN_BENCH_LAPS) ? 2 : 0;
    cfg.ai_steer_ddeg = ai_steer_on_ ? static_cast<int32_t>(ai_steer_deg_ * 10.0f + (ai_steer_deg_ >= 0 ? 0.5f : -0.5f)) : 0;
    cfg.motor_cmd_permille = (bench_type_ == RUN_BENCH_MOTOR || bench_type_ == RUN_DEMO) ? static_cast<int32_t>(bench_duty_ * 1000.0f + 0.5f) : 0;
    cfg.drs_phase = drs;
    o.drs_phase = drs;
    o.state = st; o.fault_flags = sr.fault_flags; o.worst = sr.worst; o.permits_drive = sr.permits_drive;
    o.steering_deg = steering_cmd_; o.steer_source = src;
    std::memcpy(o.flaps, ao.target, sizeof(o.flaps));
    o.motor_duty = out_duty; o.motor_braking = motor_.braking(); o.motor_derating = motor_.derating();
    o.lapping = lapping;
    o.run_state = run_state_; o.remote_run = bench_type_ != RUN_OFF && bench_remote_;
    o.track_frac = track_.fraction(); o.lap = track_.lap; o.track_flags = tflags;
    o.profile_duty = lapping ? tcmd.duty : 0; o.latg_model = lapping ? smp.latg_model : 0;
    o.cur_lap_ms = track_.current_lap_ms(now); o.last_lap_ms = track_.last_lap_ms; o.best_lap_ms = track_.best_lap_ms;
    o.odometer_m = track_.odometer_m; o.cal_phase = dyno_.phase; o.lap_event = lap_event;
    o.ai_reason = new_rec ? ao.ai_reason : last_ai_reason_; o.new_ai_rec = new_rec; o.ai_applied = ao.ai_applied;
    o.tc_cut = tc_.cut(); o.tc_active = tc_.active(); o.aero_straight = straight_now;
    o.ground_link_ok = ground_ok_;
    o.knob_pos = knob_pos_;
    o.manual_duty = (bench_type_ == RUN_BENCH_MOTOR || bench_type_ == RUN_DEMO) ? bench_duty_ : 0.0f;
    o.model_speed_kmh = speed_model_on_ ? speed_model_.v_kmh : NAN;
    if (mode_changed_) { events_ |= EV_MODE_CHANGED; mode_changed_ = false; }
    o.events = events_; events_ = 0;
    return o;
  }

  VcuModeStatus mode_status(const VcuOutputs &o) const {
    VcuModeStatus m{};
    m.drive_mode = cfg.snap.drive_mode; m.hw_profile = cfg.hw_profile; m.run_laps = cfg.snap.run_laps;
    m.tc_cut_pct = clampU8(o.tc_cut * 100.0f + 0.5f); m.knob = static_cast<int16_t>(knob_pos_);
    if (o.motor_power) m.flags |= MF_MOTOR_POWER;
    if (kill_switch_) m.flags |= MF_KILL_SWITCH_FITTED;
    if (o.remote_run) m.flags |= MF_REMOTE_RUN;
    if (o.tc_active) m.flags |= MF_TC_ACTIVE;
    if (o.ground_link_ok) m.flags |= MF_GROUND_LINK_OK;
    if (o.aero_straight) m.flags |= MF_AERO_STRAIGHT;
    if (encoder_) m.flags |= MF_ENCODER_FITTED;
    return m;
  }
  uint16_t lap_count() const { return track_.lap; }
  uint32_t last_lap_ms() const { return track_.last_lap_ms; }
  bool take_lap_committed() { bool c = lap_committed_; lap_committed_ = false; return c; }

 private:
  void stop_bench() {
    if (bench_type_ == RUN_DYNO_CAL) dyno_.abort();
    bench_type_ = RUN_OFF; bench_remote_ = false;
  }

  Supervisor sup_;
  SafetyManager safety_;
  ActiveAeroController aero_;
  MotorController motor_{false};
  PositionMonitor pos_mon_[SERVO_COUNT];
  TrackRunner track_;
  StallDetector stall_;
  DynoCalibrator dyno_;
  TractionControl tc_;
  bool kill_switch_ = false, encoder_ = false;
  uint32_t self_test_mask_ = 0;
  float steering_cmd_ = CFG_STEERING_FAILSAFE_DEG;
  float aero_prev_[4] = {0, 0, 0, 0};
  uint32_t last_ai_ts_seen_ = 0xFFFFFFFFu;
  AiReason last_ai_reason_ = AI_NONE_RECEIVED;
  uint8_t run_state_ = RUN_OFF, bench_type_ = RUN_OFF;
  bool bench_remote_ = false;
  float bench_duty_ = 0;
  uint16_t bench_laps_ = 0;
  uint32_t bench_start_ms_ = 0;
  bool stall_lockout_ = false;
  uint32_t stall_flag_until_ = 0, remote_loss_until_ = 0;
  bool estop_cmd_ = false, reset_cmd_ = false;
  bool last_permits_drive_ = false, ground_ok_ = false;
  bool mode_changed_ = false, lap_committed_ = false;
  int32_t knob_pos_ = 0;
  bool ai_steer_on_ = false, ai_steer_remote_ = false;      // FW 2.3.12 AI steering (key 27)
  float ai_steer_deg_ = 0; uint32_t ai_steer_ms_ = 0, ai_steer_block_until_ms_ = 0;
  bool preview_on_ = false;
  uint8_t preview_key_ = 0;
  uint16_t preview_us_ = 0;
  uint32_t preview_start_ms_ = 0;
  uint32_t events_ = 0;
  bool drs_on_ = false;
  uint32_t drs_start_ms_ = 0;
  uint8_t drs_phase_ = 0;
  bool demo_drs_fired_ = false, speed_model_on_ = false, demo_lap_ = false;
  uint8_t demo_prev_mode_ = 0;
  float demo_steer_ = 0, demo_hold_ = 0, demo_pending_ = 0, demo_tight_deg_ = 3.0f;
  uint32_t demo_hold_ms_ = 0;
  float demo_vmax_kmh() const {
    return speed_model_on_ ? DutySpeedModel::vmaxKmh() : cfg.dyno_vmax_ckmh > 0 ? cfg.dyno_vmax_ckmh / 100.0f : DutySpeedModel::vmaxKmh();
  }
  DutySpeedModel speed_model_;
};

