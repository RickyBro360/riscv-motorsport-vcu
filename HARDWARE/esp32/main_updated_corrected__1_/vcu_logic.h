inline float clampf(float v, float lo, float hi) { return v < lo ? lo : (v > hi ? hi : v); }
/* Age of a timestamp written by ANOTHER task (FW 2.2.9 fix, bug #22). If that task stored its
 * millis() after this task read `now`, now - t wraps to ~4e9 and a perfectly fresh value
 * looks ancient (it raised a false WATCHDOG -> E-STOP). A "future" timestamp is age 0. */
inline uint32_t ageMs(uint32_t now_ms, uint32_t t_ms) {
  return static_cast<int32_t>(now_ms - t_ms) < 0 ? 0u : now_ms - t_ms;
}
inline bool finite(float v) { return std::isfinite(v); }
inline int16_t clampI16(float v) {
  if (!std::isfinite(v)) return 0;
  if (v > 32767.0f) return 32767;
  if (v < -32768.0f) return -32768;
  // Round half away from zero. Truncation was used until Stage 2 and was
  // found (by the host parity test) to turn e.g. 12.3 deg into 1229 centi-deg
  // on one side and 1230 on the other, because 12.3*100 is 1229.9999... in
  // IEEE double. Python mirror: raspberry_pi/main.py _round_half_away().
  return static_cast<int16_t>(std::lround(v));
}
inline uint16_t clampU16(float v) {
  if (!std::isfinite(v) || v < 0.0f) return 0;
  if (v > 65535.0f) return 65535;
  return static_cast<uint16_t>(std::lround(v));  // round half away from zero, as clampI16
}
/* clampU8 deliberately still TRUNCATES: confidence bytes (conf*255) and
 * percentages — matches Python int(); b/255*255 round-trips exactly. */
inline uint8_t clampU8(float v) {
  if (!std::isfinite(v) || v < 0.0f) return 0;
  if (v > 255.0f) return 255;
  return static_cast<uint8_t>(v);
}
inline void putU16(uint8_t *b, uint16_t v) { b[0] = v & 0xFF; b[1] = (v >> 8) & 0xFF; }
inline void putI16(uint8_t *b, int16_t v) { putU16(b, static_cast<uint16_t>(v)); }
inline void putU32(uint8_t *b, uint32_t v) {
  b[0] = v & 0xFF; b[1] = (v >> 8) & 0xFF; b[2] = (v >> 16) & 0xFF; b[3] = (v >> 24) & 0xFF;
}
inline uint16_t getU16(const uint8_t *b) { return static_cast<uint16_t>(b[0] | (b[1] << 8)); }
inline int16_t getI16(const uint8_t *b) { return static_cast<int16_t>(getU16(b)); }
inline uint32_t getU32(const uint8_t *b) {
  return static_cast<uint32_t>(b[0]) | (static_cast<uint32_t>(b[1]) << 8) |
         (static_cast<uint32_t>(b[2]) << 16) | (static_cast<uint32_t>(b[3]) << 24);
}
/* rate limiter: move `current` toward `target` by at most rate*dt */
inline float slew(float current, float target, float rate_per_s, float dt_s) {
  float step = rate_per_s * dt_s;
  return current + clampf(target - current, -step, step);
}

// =============================================================================
// 3. VEHICLE STATE MACHINE
//    Enum ORDER IS WIRE FORMAT (CAN 0x100 byte 0). raspberry_pi/main.py's
//    _VCU_STATE_BY_INDEX and Ground Station/bridge.py depend on it.
// =============================================================================
enum VehicleState : uint8_t {
  VS_BOOT = 0, VS_INIT = 1, VS_SELF_TEST = 2, VS_IDLE = 3, VS_ARMED = 4,
  VS_DRIVE = 5, VS_FAULT = 6, VS_EMERGENCY_STOP = 7, VS_SHUTDOWN = 8,
};

enum VehicleEvent : uint8_t {
  VE_BOOT_DONE, VE_INIT_DONE, VE_SELF_TEST_PASS, VE_SELF_TEST_FAIL,
  VE_ARM_REQUEST, VE_DISARM_REQUEST, VE_DRIVE_ENABLE,
  VE_FAULT_RAISED, VE_CRITICAL_FAULT, VE_FAULT_CLEARED,
  VE_ESTOP_REQUEST, VE_ESTOP_RESET_REQUEST, VE_SHUTDOWN_REQUEST,
};

inline const char *stateName(VehicleState s) {
  static const char *names[] = {"BOOT", "INIT", "SELF_TEST", "IDLE", "ARMED",
                                "DRIVE", "FAULT", "EMERGENCY_STOP", "SHUTDOWN"};
  return (s <= VS_SHUTDOWN) ? names[s] : "UNKNOWN";
}

/* Pure transition function. Unlisted (state,event) pairs = no change.
 * Two deliberately forbidden shortcuts (asserted in the host tests):
 *   FAULT          -> never straight to ARMED/DRIVE (clears to IDLE only)
 *   EMERGENCY_STOP -> never straight to IDLE/ARMED/DRIVE (reset re-runs INIT) */
inline VehicleState stateTransition(VehicleState s, VehicleEvent e) {
  if (s == VS_SHUTDOWN) return s;
  if (e == VE_SHUTDOWN_REQUEST) return VS_SHUTDOWN;
  // Highest priority: emergency stop / critical faults from ANY state.
  if (e == VE_ESTOP_REQUEST || e == VE_CRITICAL_FAULT) return VS_EMERGENCY_STOP;
  if (s == VS_EMERGENCY_STOP) return (e == VE_ESTOP_RESET_REQUEST) ? VS_INIT : s;
  if (e == VE_FAULT_RAISED) return VS_FAULT;
  switch (s) {
    case VS_BOOT:      return e == VE_BOOT_DONE ? VS_INIT : s;
    case VS_INIT:      return e == VE_INIT_DONE ? VS_SELF_TEST : s;
    case VS_SELF_TEST:
      if (e == VE_SELF_TEST_PASS) return VS_IDLE;
      if (e == VE_SELF_TEST_FAIL) return VS_FAULT;
      return s;
    case VS_IDLE:      return e == VE_ARM_REQUEST ? VS_ARMED : s;
    case VS_ARMED:
      if (e == VE_DISARM_REQUEST) return VS_IDLE;
      if (e == VE_DRIVE_ENABLE) return VS_DRIVE;
      return s;
    case VS_DRIVE:     return e == VE_DISARM_REQUEST ? VS_IDLE : s;
    case VS_FAULT:     return e == VE_FAULT_CLEARED ? VS_IDLE : s;
    default:           return s;
  }
}

inline bool stateAllowsActuation(VehicleState s) { return s == VS_ARMED || s == VS_DRIVE; }
inline bool stateAllowsMotor(VehicleState s) { return s == VS_DRIVE; }
inline bool stateIsSafeOverride(VehicleState s) {
  return s == VS_FAULT || s == VS_EMERGENCY_STOP || s == VS_SHUTDOWN;
}

