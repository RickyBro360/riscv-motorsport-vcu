inline float wheelSpeedKmhFromPeriod(uint32_t period_us, float diameter_m, uint8_t ppr) {
  if (period_us == 0 || ppr == 0) return 0.0f;
  float rev_per_s = 1e6f / (static_cast<float>(period_us) * ppr);
  return rev_per_s * (3.14159265f * diameter_m) * 3.6f;
}

/* Complementary filter roll/pitch (deg). Axes: X forward, Y left, Z up. */
struct Attitude {
  float roll = 0, pitch = 0, yaw = 0;
  bool initialised = false;
  void update(float ax, float ay, float az, float gx_dps, float gy_dps, float gz_dps, float dt_s,
              float alpha = 0.98f) {
    if (!finite(ax) || !finite(ay) || !finite(az)) return;
    float acc_roll = std::atan2(ay, az) * 57.29578f;
    float acc_pitch = std::atan2(-ax, std::sqrt(ay * ay + az * az)) * 57.29578f;
    if (!initialised) { roll = acc_roll; pitch = acc_pitch; initialised = true; return; }
    roll = alpha * (roll + gx_dps * dt_s) + (1.0f - alpha) * acc_roll;
    pitch = alpha * (pitch + gy_dps * dt_s) + (1.0f - alpha) * acc_pitch;
    yaw += gz_dps * dt_s;  // gyro-only: drifts, no magnetometer in the BOM
    if (yaw >= 360.0f) yaw -= 360.0f;
    if (yaw < 0.0f) yaw += 360.0f;
  }
};

/* FW 2.3.13: gyro zero-rate trim, learned whenever the car stands still.
 * The MPU6050's zero rate wanders with temperature (often 0.5-3 deg/s), and yaw has no magnetometer to correct it,
 * so any leftover offset turns into a steady yaw drift. Fed the car-frame gyro and accel at 100 Hz; every 1 s window
 * in which the gyro is steady (std-dev < STILL_STD_DPS on all axes, mean < MAX_TRIM_DPS) and the accel shows only
 * gravity (|a| 0.9..1.1 g, changing < 0.04 g) counts as still: the window's mean rate becomes the trim
 * (first time directly, then averaged). A steady-but-moving car would need a perfectly constant turn rate with no
 * vibration for a full second, which does not happen; a running motor vibrates the car well above the threshold. */
struct GyroStillTrim {
  static constexpr int WINDOW = 100;              // samples (1 s at 100 Hz)
  static constexpr float STILL_STD_DPS = 0.35f;
  static constexpr float MAX_TRIM_DPS = 5.0f;
  float trim[3] = {0, 0, 0};
  bool learned = false;
  uint32_t still_windows = 0;
  int n = 0;
  double sum[3] = {0, 0, 0}, sq[3] = {0, 0, 0};
  float amin = 99.0f, amax = 0.0f;
  void reset(bool keep_trim = false) {
    if (!keep_trim) { trim[0] = trim[1] = trim[2] = 0; learned = false; }
    n = 0; for (int k = 0; k < 3; ++k) { sum[k] = 0; sq[k] = 0; } amin = 99.0f; amax = 0.0f;
  }
  bool window_starting() const { return n == 0; }
  // g: car-frame gyro BEFORE trim (deg/s); a: car-frame accel (g). Returns 0 mid-window, 1 window ended moving,
  // 2 window ended still (trim updated).
  int feed(const float g[3], const float a[3]) {
    if (!finite(g[0]) || !finite(g[1]) || !finite(g[2]) || !finite(a[0]) || !finite(a[1]) || !finite(a[2])) { reset(true); return 1; }
    for (int k = 0; k < 3; ++k) { sum[k] += g[k]; sq[k] += static_cast<double>(g[k]) * g[k]; }
    const float an = std::sqrt(a[0] * a[0] + a[1] * a[1] + a[2] * a[2]);
    amin = std::min(amin, an); amax = std::max(amax, an);
    if (++n < WINDOW) return 0;
    bool still = amin > 0.9f && amax < 1.1f && amax - amin < 0.04f;
    float mean[3];
    for (int k = 0; k < 3; ++k) {
      mean[k] = static_cast<float>(sum[k] / n);
      const double var = sq[k] / n - static_cast<double>(mean[k]) * mean[k];
      if (var > STILL_STD_DPS * STILL_STD_DPS || std::fabs(mean[k]) > MAX_TRIM_DPS) still = false;
    }
    reset(true);
    if (!still) return 1;
    for (int k = 0; k < 3; ++k) trim[k] = learned ? 0.5f * trim[k] + 0.5f * mean[k] : mean[k];
    learned = true; ++still_windows;
    return 2;
  }
  void apply(float g[3]) const { for (int k = 0; k < 3; ++k) g[k] -= trim[k]; }
};

/* Longitudinal slip from driven vs undriven wheels, in per-mille.
 *   slip = (driven - undriven) / max(undriven, floor)
 * Positive = wheelspin under power, negative = lock-up under braking. Below
 * CFG_SLIP_MIN_SPEED_KMH the ratio is meaningless (dividing by ~0), so it
 * reports 0. Rear-wheel drive assumed: driven = rear pair, reference = front
 * pair (see CFG_DRIVEN_AXLE_REAR). */
inline int16_t slipRatioPermille(float fl, float fr, float rl, float rr) {
  float driven = CFG_DRIVEN_AXLE_REAR ? (rl + rr) * 0.5f : (fl + fr) * 0.5f;
  float reference = CFG_DRIVEN_AXLE_REAR ? (fl + fr) * 0.5f : (rl + rr) * 0.5f;
  if (!finite(driven) || !finite(reference)) return 0;
  if (reference < CFG_SLIP_MIN_SPEED_KMH && driven < CFG_SLIP_MIN_SPEED_KMH) return 0;
  float denom = reference > CFG_SLIP_MIN_SPEED_KMH ? reference : CFG_SLIP_MIN_SPEED_KMH;
  return clampI16(clampf((driven - reference) / denom, -2.0f, 2.0f) * 1000.0f);
}

/* First-order thermal estimate: fits dT/dt from the observed temperature rise
 * and extrapolates to the limit. Deliberately simple — it answers "at the
 * current trend, how long until the limit?", not "what is the thermal model of
 * this motor". Returns THERMAL_NO_LIMIT when not warming (or already over). */
constexpr uint16_t THERMAL_NO_LIMIT = 0xFFFF;

class ThermalEstimator {
 public:
  /* temp_c sampled every dt_s (call at a steady rate). */
  uint16_t update(float temp_c, float limit_c, uint32_t now_ms) {
    if (!finite(temp_c)) return THERMAL_NO_LIMIT;
    if (have_sample_) {
      uint32_t dt_ms = now_ms - last_ms_;
      if (dt_ms >= CFG_THERMAL_SAMPLE_MS) {
        float rate = (temp_c - last_temp_) / (dt_ms / 1000.0f);   // deg C per second
        // heavy smoothing: sensor quantisation is 0.0625 C, the trend is slow
        rate_dps_ = finite(rate_dps_) ? (1.0f - CFG_THERMAL_ALPHA) * rate_dps_ + CFG_THERMAL_ALPHA * rate
                                      : rate;
        last_temp_ = temp_c;
        last_ms_ = now_ms;
      }
    } else {
      // millis() is 0 right after boot, so a timestamp cannot be the "no sample
      // yet" sentinel — use an explicit flag.
      have_sample_ = true;
      last_temp_ = temp_c;
      last_ms_ = now_ms;
      return THERMAL_NO_LIMIT;
    }
    if (temp_c >= limit_c) return 0;
    if (!finite(rate_dps_) || rate_dps_ <= CFG_THERMAL_MIN_RATE_DPS) return THERMAL_NO_LIMIT;
    float seconds = (limit_c - temp_c) / rate_dps_;
    if (seconds >= static_cast<float>(THERMAL_NO_LIMIT - 1)) return THERMAL_NO_LIMIT;
    return static_cast<uint16_t>(seconds);
  }
  float rate_c_per_s() const { return rate_dps_; }

 private:
  float last_temp_ = 0, rate_dps_ = NAN;
  uint32_t last_ms_ = 0;
  bool have_sample_ = false;
};

// =============================================================================
// 10b. VIBRATION LEVEL (Stage 2d)
//      RMS of the acceleration magnitude around its slow-moving mean, in milli-g.
//      On the dyno this is the one "chassis" signal the IMU still carries:
//      wheel imbalance, a loose mount or roller resonance all show up here.
// =============================================================================
class VibrationMeter {
 public:
  /* call at a fixed rate (100 Hz in the sensor task) */
  float update(float ax, float ay, float az) {
    if (!finite(ax) || !finite(ay) || !finite(az)) return rms_mg_;
    float mag = std::sqrt(ax * ax + ay * ay + az * az);
    if (!init_) { mean_ = mag; init_ = true; }
    mean_ += 0.01f * (mag - mean_);            // ~1 s time constant: gravity + slow tilt
    float d = (mag - mean_) * 1000.0f;         // milli-g
    var_ += 0.05f * (d * d - var_);            // ~0.2 s window
    rms_mg_ = std::sqrt(var_ > 0 ? var_ : 0);
    return rms_mg_;
  }
  float rms_mg() const { return rms_mg_; }

 private:
  bool init_ = false;
  float mean_ = 1.0f, var_ = 0.0f, rms_mg_ = 0.0f;
};

