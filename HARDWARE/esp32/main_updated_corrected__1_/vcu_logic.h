/* FW 2.3.4 — wheel speed ESTIMATED from the applied motor duty (the hobby hall modules are too
 * unreliable to show). Free-running geared DC motor: speed ~ duty above the dead band, first-order
 * lag for spin-up / coast-down. It is an estimate, reported as such (RO key 106 = 1). */
struct DutySpeedModel {
  float v_kmh = 0;
  static float vmaxKmh() { return VCU_CAL_MOTOR_MAX_RPM / 60.0f * 3.14159265f * (VCU_CAL_WHEEL_DIAMETER_MM / 1000.0f) * 3.6f; }
  float update(float duty, float dt_s) {
    const float target = duty * 100.0f >= VCU_CAL_MOTOR_MIN_DUTY_PCT ? clampf(duty, 0.0f, 1.0f) * vmaxKmh() : 0.0f;
    const float k = clampf(dt_s / 0.4f, 0.0f, 1.0f);
    v_kmh += (target - v_kmh) * k;
    if (v_kmh < 0.02f && target == 0.0f) v_kmh = 0.0f;
    return v_kmh;
  }
};

/* FW 2.3.4 — demo corner sequence, run BY THE VCU (key 26 / console `demo`). Times in ms from the
 * start. lo = just above the motor's dead band, top = demo top duty (both 0..1).
 *   0-2 s    accelerate lo -> cruise      2-4 s   hold cruise        4-5.5 s  brake to lo
 *   5.5-7.5  steer LEFT                   7.5-9.5 steer RIGHT        9.5-10.5 straighten
 *   10.5-13  accelerate to top            13 s    DRS (5 s flat + 1 s max, the normal DRS timer)
 *   13-19    hold top                     19-21   slow to lo, then stop
 * The flaps are NOT scripted: they follow the steering law and the DRS exactly as in normal use. */
struct DemoCmd { float duty = 0; float steer_frac = 0; bool drs = false; bool done = false; };
constexpr uint32_t DEMO_TOTAL_MS = 21000;
inline DemoCmd demoSequence(uint32_t t, float lo, float top) {
  DemoCmd d;
  const float cruise = lo + (top - lo) * 0.6f;
  auto ramp = [](uint32_t t, uint32_t a, uint32_t b, float y0, float y1) {
    return y0 + (y1 - y0) * clampf((static_cast<float>(t) - a) / static_cast<float>(b - a), 0.0f, 1.0f);
  };
  if (t < 2000) d.duty = ramp(t, 0, 2000, lo, cruise);
  else if (t < 4000) d.duty = cruise;
  else if (t < 5500) d.duty = ramp(t, 4000, 5500, cruise, lo);
  else if (t < 10500) { d.duty = lo; d.steer_frac = t < 7500 ? 0.8f : t < 9500 ? -0.8f : 0.0f; }
  else if (t < 13000) d.duty = ramp(t, 10500, 13000, lo, top);
  else if (t < 19000) { d.duty = top; d.drs = true; }
  else if (t < DEMO_TOTAL_MS) d.duty = ramp(t, 19000, DEMO_TOTAL_MS, top, lo);
  else { d.duty = lo; d.done = true; }
  return d;
}

