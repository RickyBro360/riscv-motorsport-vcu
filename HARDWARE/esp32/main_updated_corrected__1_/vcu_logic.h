struct SupervisorInputs {
  uint32_t now_ms = 0;
  SafetyResult safety;
  bool driver_fresh = false;
  bool arm_requested = false;    // DRV_FLAG_ARM held
  bool estop_requested = false;  // DRV_FLAG_ESTOP or local serial/command
  bool estop_reset_requested = false;
  int16_t throttle_permille = 0;
};

class Supervisor {
 public:
  VehicleState state() const { return state_; }
  void force(VehicleState s) { state_ = s; }
  void event(VehicleEvent e) { state_ = stateTransition(state_, e); }

  VehicleState step(const SupervisorInputs &in) {
    if (in.estop_requested) { event(VE_ESTOP_REQUEST); return state_; }
    if (in.safety.worst >= SEV_CRITICAL) { event(VE_CRITICAL_FAULT); return state_; }

    if (state_ == VS_EMERGENCY_STOP) {
      // reset only when the operator released ARM and nothing critical remains
      if (in.estop_reset_requested && !in.arm_requested) event(VE_ESTOP_RESET_REQUEST);
      return state_;
    }
    if (in.safety.worst >= SEV_FAULT && state_ >= VS_IDLE && state_ != VS_FAULT) {
      event(VE_FAULT_RAISED);
      clear_.active = false;
      return state_;
    }
    if (state_ == VS_FAULT) {
      if (clear_.update(in.safety.worst < SEV_FAULT && !in.arm_requested, in.now_ms, CFG_FAULT_CLEAR_HOLD_MS))
        event(VE_FAULT_CLEARED);
      return state_;
    }
    bool neutral = std::fabs(in.throttle_permille) < CFG_THROTTLE_NEUTRAL_PERMILLE;
    switch (state_) {
      case VS_IDLE:
        if (in.arm_requested && in.driver_fresh && neutral) { event(VE_ARM_REQUEST); neutral_.active = false; }
        break;
      case VS_ARMED:
        if (!in.arm_requested || !in.driver_fresh) event(VE_DISARM_REQUEST);
        else if (neutral_.update(neutral, in.now_ms, CFG_ARM_NEUTRAL_HOLD_MS)) event(VE_DRIVE_ENABLE);
        break;
      case VS_DRIVE:
        if (!in.arm_requested) event(VE_DISARM_REQUEST);
        break;
      default: break;
    }
    return state_;
  }

 private:
  VehicleState state_ = VS_BOOT;
  Persist clear_, neutral_;
};

