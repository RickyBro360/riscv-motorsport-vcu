// =============================================================================
// 10d. TRACK RUNNER (Stage 2d) — the car "drives" a stored circuit on the dyno
//      Position = rear-wheel odometry (hall pulses) mapped onto the selected
//      track: one lap = `lap_length_cm` of wheel travel. At each position the map
//      gives the road-wheel steering angle, the modelled speed (-> motor duty),
//      straight/corner aero mode and the modelled lateral g (-> asymmetric flaps).
//      Runs ON THE VCU so actuators, position and the dashboard can never drift
//      apart: the dashboard draws the car at the position this code reports.
// =============================================================================
struct TrackSample {
  float steer_deg = 0;       // + = left
  float speed_frac = 0;      // 0..1 of the track's modelled vmax
  float latg_model = 0;      // modelled lateral g at full scale, + = left
  bool straight_map = false; // map flag, before offsets
  bool straight = false;     // after the open-delay / close-early offsets
  bool braking = false;
  uint8_t sector = 0;
};

inline const TrackPoint &trackPoint(uint8_t track, int idx) {
  const TrackInfo &t = TRACKS[track < TRACK_COUNT ? track : TRACK_DEFAULT_ID];
  idx %= TRACK_POINTS; if (idx < 0) idx += TRACK_POINTS;
  return t.pts[idx];
}

inline bool trackFlagAt(uint8_t track, float frac, uint8_t flag) {
  float f = frac - std::floor(frac);
  int idx = static_cast<int>(f * TRACK_POINTS + 0.5f);
  return (trackPoint(track, idx).flags & flag) != 0;
}

/* Linear interpolation between the two neighbouring samples. */
inline TrackSample trackSample(uint8_t track, float frac, const Tunables &tun) {
  TrackSample o;
  if (!finite(frac)) frac = 0;
  float f = frac - std::floor(frac);
  float x = f * TRACK_POINTS;
  int i0 = static_cast<int>(x);
  float w = x - i0;
  const TrackPoint &a = trackPoint(track, i0), &b = trackPoint(track, i0 + 1);
  o.steer_deg = ((1 - w) * a.steer_q + w * b.steer_q) * 0.25f;
  o.speed_frac = ((1 - w) * a.speed_q + w * b.speed_q) / 255.0f;
  o.latg_model = ((1 - w) * a.latg_q + w * b.latg_q) * 0.05f;
  const TrackPoint &n = w < 0.5f ? a : b;
  o.straight_map = (n.flags & TRACK_F_STRAIGHT) != 0;
  o.braking = (n.flags & TRACK_F_BRAKING) != 0;
  o.sector = (n.flags >> TRACK_F_SECTOR_SHIFT) & 0x03;
  const TrackInfo &t = TRACKS[track < TRACK_COUNT ? track : TRACK_DEFAULT_ID];
  float len = static_cast<float>(t.length_m);
  float open_df = tun.straight_open_delay_m / len, close_df = tun.straight_close_early_m / len;
  o.straight = o.straight_map && trackFlagAt(track, f - open_df, TRACK_F_STRAIGHT) &&
               trackFlagAt(track, f + close_df, TRACK_F_STRAIGHT);
  return o;
}

/* Map sample + tunables -> the physical commands for this instant. */
struct TrackCommand {
  float steer_deg = 0;
  float duty = 0;               // motor duty 0..1 the profile asks for
  float flaps[4] = {0, 0, 0, 0};
  bool straight_front = false, straight_rear = false;
};

/* FW 2.3.8 — lap length (cm of wheel travel) that makes ONE lap of `track` take about `seconds`
 * when the car follows the map's speed profile: time = L / vmax * integral(df / duty(f)). */
/* FW 2.3.9 demo-lap speed: squared, so braking zones drop clearly; never inside the motor's dead band. */
inline float demoLapDuty(float speed_frac, const Tunables &tun) {
  const float top = std::min(tun.duty_cap_permille / 1000.0f, VCU_CAL_DEMO_LAP_TOP_DUTY_PCT / 100.0f);
  const float lo = std::min(top, (VCU_CAL_MOTOR_MIN_DUTY_PCT + 5) / 100.0f);
  const float f = clampf(speed_frac, 0.0f, 1.0f);
  return lo + (top - lo) * f * f;
}
/* FW 2.3.9 demo-lap steering TARGET in degrees (+ = left). The map's real steering angles are tiny on a
 * circuit this fast (long corners 0.5-2.4 deg, chicanes a few hundred ms), so the demo shows them as:
 * tight corner (>= 3 deg in the map, looked for +-1.6 % of a lap around the car) = full lock,
 * long corner (>= 0.3 deg) = half lock, else straight. The caller smooths it. */
/* Largest steering angle anywhere in a circuit's map (deg). */
inline float trackMaxSteerDeg(uint8_t track, const Tunables &tun) {
  float mx = 0;
  for (int i = 0; i < 250; ++i) mx = std::max(mx, std::fabs(trackSample(track, (i + 0.5f) / 250, tun).steer_deg));
  return mx;
}
inline float demoLapSteerTarget(uint8_t track, float frac, const Tunables &tun, float lock_deg, float tight_deg = 3.0f) {
  float best = 0;
  for (int k = -4; k <= 4; ++k) {
    float f = frac + k * 0.004f; f -= std::floor(f);
    const float sd = trackSample(track, f, tun).steer_deg;
    if (std::fabs(sd) > std::fabs(best)) best = sd;
  }
  const float mag = std::fabs(best);
  // FW 2.3.10: `tight_deg` is set per circuit (a twisty circuit needs more map angle for full lock), and
  // between "long corner" and "tight" the steering grows from half lock to full lock.
  const float half = VCU_CAL_DEMO_LAP_HALF_LOCK_PCT / 100.0f;
  const float out = mag >= tight_deg ? lock_deg : mag >= 0.3f ? lock_deg * std::max(half, mag / tight_deg) : 0.0f;
  return best < 0 ? -out : out;
}
inline int32_t demoLapLengthCm(uint8_t track, const Tunables &tun, float vmax_kmh, float seconds) {
  const int N = 400; float sum = 0;
  for (int i = 0; i < N; ++i) {
    const TrackSample smp = trackSample(track, (i + 0.5f) / N, tun);
    const float duty = clampf(demoLapDuty(smp.speed_frac, tun), 0.2f, 1.0f);
    sum += 1.0f / (N * duty);
  }
  const float len_m = seconds * (vmax_kmh / 3.6f) / (sum > 0 ? sum : 1.0f);
  return static_cast<int32_t>(clampf(len_m * 100.0f, 500.0f, 100000.0f));
}

class TrackRunner {
 public:
  uint8_t track_id = TRACK_DEFAULT_ID;
  float lap_length_m = 60.0f;
  // position
  float lap_dist_m = 0;         // distance into the current lap (dyno metres)
  double odometer_m = 0;        // total since boot
  uint16_t lap = 0;             // completed laps this run
  // timing (ms)
  uint32_t lap_start_ms = 0, last_lap_ms = 0, best_lap_ms = 0;
  bool running = false;
  bool lap_completed_event = false;  // true for one update after a start/finish crossing

  void start(uint8_t track, float lap_len_m, uint32_t now_ms) {
    track_id = track < TRACK_COUNT ? track : TRACK_DEFAULT_ID;
    lap_length_m = lap_len_m > 1.0f ? lap_len_m : 60.0f;
    lap_dist_m = 0; lap = 0; lap_start_ms = now_ms; last_lap_ms = 0; best_lap_ms = 0;
    running = true; lap_completed_event = false; rear_straight_ = false; rear_changing_ = false;
  }
  void stop() { running = false; }

  /* Feed wheel travel since the last call. Always integrates the odometer; the
   * lap position only moves while running. */
  void advance(float dist_m, uint32_t now_ms) {
    lap_completed_event = false;
    if (!finite(dist_m) || dist_m < 0) return;
    odometer_m += dist_m;
    if (!running) return;
    lap_dist_m += dist_m;
    if (lap_dist_m >= lap_length_m) {
      lap_dist_m -= lap_length_m;
      if (lap_dist_m >= lap_length_m) lap_dist_m = 0;  // absurd jump: restart the lap
      last_lap_ms = now_ms - lap_start_ms;
      if (best_lap_ms == 0 || last_lap_ms < best_lap_ms) best_lap_ms = last_lap_ms;
      lap_start_ms = now_ms;
      ++lap;
      lap_completed_event = true;
    }
  }
  float fraction() const { return lap_length_m > 0 ? clampf(lap_dist_m / lap_length_m, 0.0f, 0.99999f) : 0.0f; }
  uint32_t current_lap_ms(uint32_t now_ms) const { return running ? now_ms - lap_start_ms : 0; }

  /* The rear flaps follow the front with a short delay so four servos never start
   * moving in the same instant (current peak on the 2.2 A bench adapter). */
  TrackCommand command(const Tunables &tun, uint32_t now_ms, TrackSample *sample_out = nullptr) {
    TrackSample s = trackSample(track_id, fraction(), tun);
    if (sample_out) *sample_out = s;
    TrackCommand c;
    c.steer_deg = clampf(s.steer_deg * tun.steer_gain_permille / 1000.0f, -CFG_STEERING_MAX_DEG, CFG_STEERING_MAX_DEG);
    float cap = tun.duty_cap_permille / 1000.0f, floor_ = tun.duty_floor_permille / 1000.0f;
    c.duty = clampf(floor_ + (cap - floor_) * clampf(s.speed_frac, 0, 1), 0.0f, cap);
    c.straight_front = s.straight;
    if (s.straight != rear_straight_) {
      if (!rear_changing_) { rear_changing_ = true; rear_change_ms_ = now_ms; }  // millis() may be 0: use a flag
      if (now_ms - rear_change_ms_ >= REAR_STAGGER_MS) { rear_straight_ = s.straight; rear_changing_ = false; }
    } else {
      rear_changing_ = false;
    }
    c.straight_rear = rear_straight_;
    float front = (c.straight_front ? tun.straight_front_cdeg : tun.corner_front_cdeg) / 100.0f;
    float rear = (c.straight_rear ? tun.straight_rear_cdeg : tun.corner_rear_cdeg) / 100.0f;
    // Asymmetric term: same sign convention as aeroBaseline() (+lat g = turning left
    // raises the RIGHT flaps). Only in corner mode — straight mode is symmetric.
    float lat = 0;
    if (!c.straight_front)
      lat = clampf(s.latg_model * tun.asym_gain_cdeg_per_g / 100.0f, -CFG_AERO_LATERAL_MAX_DEG, CFG_AERO_LATERAL_MAX_DEG);
    c.flaps[AERO_LF] = clampf(front - lat, CFG_WING_ANGLE_MIN_DEG, CFG_WING_ANGLE_MAX_DEG);
    c.flaps[AERO_RF] = clampf(front + lat, CFG_WING_ANGLE_MIN_DEG, CFG_WING_ANGLE_MAX_DEG);
    c.flaps[AERO_LR] = clampf(rear - (c.straight_rear ? 0 : lat), CFG_WING_ANGLE_MIN_DEG, CFG_WING_ANGLE_MAX_DEG);
    c.flaps[AERO_RR] = clampf(rear + (c.straight_rear ? 0 : lat), CFG_WING_ANGLE_MIN_DEG, CFG_WING_ANGLE_MAX_DEG);
    return c;
  }
  static constexpr uint32_t REAR_STAGGER_MS = 150;

 private:
  bool rear_straight_ = false, rear_changing_ = false;
  uint32_t rear_change_ms_ = 0;
};

/* Stall watchdog: duty applied but the driven wheels are not turning. Uses hall
 * PULSES, not the speed estimate: with one magnet per wheel the speed reads 0
 * between pulses at slow dyno speeds, which would look like a stall. */
class StallDetector {
 public:
  bool update(float duty, bool rear_pulse_seen, uint32_t now_ms) {
    if (!init_ || duty <= DUTY_MIN || rear_pulse_seen) { last_ok_ms_ = now_ms; init_ = true; return false; }
    return now_ms - last_ok_ms_ >= HOLD_MS;
  }
  static constexpr float DUTY_MIN = 0.25f;
  static constexpr uint32_t HOLD_MS = 2500;
 private:
  bool init_ = false;
  uint32_t last_ok_ms_ = 0;
};

/* Traction control (FW 2.2, track mode): rear (driven) wheels faster than the front by more
 * than the target slip -> cut motor duty in proportion. Fast attack, slower release. Needs
 * the fronts turning (CFG_TC_MIN_SPEED_KMH), so it never acts on the dyno. */
class TractionControl {
 public:
  /* returns the duty multiplier 1 - cut, in [1 - CFG_TC_MAX_CUT, 1] */
  float update(bool enabled, float front_kmh, float rear_kmh, int32_t target_permille, float dt_s, uint32_t now_ms) {
    float desired = 0.0f;
    if (enabled && target_permille > 0 && finite(front_kmh) && finite(rear_kmh) && front_kmh >= CFG_TC_MIN_SPEED_KMH) {
      float slip = (rear_kmh - front_kmh) / front_kmh;
      float over = slip - target_permille / 1000.0f;
      if (persist_.update(over > 0.0f, now_ms, CFG_TC_PERSIST_MS)) desired = clampf(over * CFG_TC_GAIN, 0.0f, CFG_TC_MAX_CUT);
    } else {
      persist_.active = false;
    }
    if (!enabled) { desired = 0.0f; cut_ = 0.0f; }
    float dt = clampf(finite(dt_s) ? dt_s : 0.0f, 0.0f, 0.1f);
    cut_ = desired > cut_ ? desired : std::max(desired, cut_ - CFG_TC_RELEASE_PER_S * dt);
    return 1.0f - cut_;
  }
  float cut() const { return cut_; }
  bool active() const { return cut_ > 0.01f; }

 private:
  float cut_ = 0.0f;
  Persist persist_;
};

// =============================================================================
// 10e. DYNO CALIBRATION (Stage 2d) — replaces the missing motor RPM label
//      Phase 1: step duty up from 10 % every 600 ms until the rear wheels turn
//               -> start duty (the lowest duty that overcomes static friction).
//      Phase 2: hold the duty cap for 3 s, average rear speed over the last 1.5 s
//               -> vmax at the cap. The dashboard scales its speed axes from it.
//      Wheels on the rollers (or off the ground), IDLE only, aborts on any fault.
// =============================================================================
class DynoCalibrator {
 public:
  enum Phase : uint8_t { IDLE = 0, FIND_START = 1, HOLD_CAP = 2, DONE = 3, FAILED = 4 };
  Phase phase = IDLE;
  float start_duty = 0, vmax_kmh = 0;

  void begin(float cap, uint32_t now_ms) {
    cap_ = clampf(cap, 0.2f, 1.0f); phase = FIND_START; duty_ = 0.10f; t_ms_ = now_ms;
    start_duty = 0; vmax_kmh = 0; sum_ = 0; n_ = 0; begin_ms_ = now_ms;
  }
  void abort() { if (phase == FIND_START || phase == HOLD_CAP) phase = FAILED; }
  bool active() const { return phase == FIND_START || phase == HOLD_CAP; }

  /* returns the duty to apply now */
  float update(float rear_kmh, uint32_t now_ms) {
    if (!active()) return 0.0f;
    if (now_ms - begin_ms_ > 25000) { phase = FAILED; return 0.0f; }
    if (phase == FIND_START) {
      if (rear_kmh > 0.3f) {
        start_duty = duty_; phase = HOLD_CAP; t_ms_ = now_ms; return cap_;
      }
      if (now_ms - t_ms_ >= 600) {
        duty_ += 0.05f; t_ms_ = now_ms;
        if (duty_ > cap_ + 1e-4f) { phase = FAILED; return 0.0f; }  // never turned: wiring/jammed
      }
      return duty_;
    }
    // HOLD_CAP
    uint32_t held = now_ms - t_ms_;
    if (held >= 1500 && finite(rear_kmh)) { sum_ += rear_kmh; ++n_; }
    if (held >= 3000) {
      vmax_kmh = n_ ? static_cast<float>(sum_ / n_) : 0.0f;
      phase = vmax_kmh > 0.1f ? DONE : FAILED;
      return 0.0f;
    }
    return cap_;
  }

 private:
  float cap_ = 0.85f, duty_ = 0.1f;
  uint32_t t_ms_ = 0, begin_ms_ = 0;
  double sum_ = 0; uint32_t n_ = 0;
};

