inline bool canDecodeDriverCommand(const CanFrame &f, uint32_t now_ms, DriverCommand &out) {
  if (f.id != CAN_ID_DRIVER_COMMAND || f.dlc < 6) return false;
  DriverCommand c;
  c.sequence = f.data[0];
  c.steering_permille = getI16(&f.data[1]);
  c.throttle_permille = getI16(&f.data[3]);
  c.flags = f.data[5];
  if (c.steering_permille < -1000 || c.steering_permille > 1000 ||
      c.throttle_permille < -1000 || c.throttle_permille > 1000) return false;
  c.rx_ms = now_ms; c.valid = true; out = c; return true;
}

