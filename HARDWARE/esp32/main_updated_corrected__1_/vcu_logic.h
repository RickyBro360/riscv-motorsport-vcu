enum Severity : uint8_t { SEV_NONE = 0, SEV_INFO, SEV_WARNING, SEV_FAULT, SEV_CRITICAL };

/* Persistence timer: condition must be continuously true for `hold_ms`. */
struct Persist {
  bool active = false;
  uint32_t since_ms = 0;
  bool update(bool cond, uint32_t now_ms, uint32_t hold_ms) {
    if (!cond) { active = false; return false; }
    if (!active) { active = true; since_ms = now_ms; }
    return (now_ms - since_ms) >= hold_ms;
  }
};

